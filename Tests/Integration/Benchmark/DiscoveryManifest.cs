using System.IO;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using NPC_Plugin_Chooser_2.BackEnd;
using NPC_Plugin_Chooser_2.Models;
using NPC_Plugin_Chooser_2.Tests.Integration.Memory;
using NPC_Plugin_Chooser_2.Tests.TestSupport;
using NPC_Plugin_Chooser_2.View_Models;

namespace NPC_Plugin_Chooser_2.Tests.Integration.Benchmark;

/// <summary>
/// Deterministic, normalized description of everything discovery produced, used to compare the legacy
/// and targeted implementations over the same real inputs. Captures:
/// <list type="bullet">
///   <item><c>faceGenCache</c> — the two discovery dictionaries handed to every consumer (loose paths per
///     source folder, archive FaceGen paths per entry), recomputed once more after the measurement;</item>
///   <item><c>modSettings</c> — the persisted entries (folders and plugins kept in their precedence order;
///     NPC/FormKey sets, FaceGen-only keys, plugin ownership, flags, snapshots sorted);</item>
///   <item><c>inMemory</c> — every in-memory entry, including mugshot-only ones the model drops;</item>
///   <item><c>npcCatalogue</c> — the NPC list as the user would see it;</item>
///   <item><c>caches</c> and <c>dialogs</c> — non-appearance/missing-master caches and warning text.</item>
/// </list>
/// Arrays are sorted unless their order carries meaning (folder/plugin precedence).
/// </summary>
internal static class DiscoveryManifest
{
    private static readonly HashSet<string> OrderedArrays = new(StringComparer.Ordinal)
    {
        "CorrespondingFolderPaths", "CorrespondingModKeys", "LockedFolderPaths", "MugShotFolderPaths",
    };

    public static async Task WriteAsync(string path, FrontendVmHarness harness, Settings settings,
        IReadOnlyList<string> dialogs)
    {
        var mods = harness.ModsVm;
        var task = Reflect.Invoke<Task<(Dictionary<string, HashSet<string>> loose, Dictionary<string, HashSet<string>> bsa)>>(
            mods, "CacheFaceGenPathsOnLoadAsync", null, null)!;
        var (loose, bsa) = await task;

        var root = new JObject
        {
            ["variant"] = FaceGenDiscovery.UseLegacyImplementation ? "legacy" : "optimized",
            ["faceGenCache"] = new JObject
            {
                ["loose"] = JObject.FromObject(loose.OrderBy(k => k.Key, StringComparer.OrdinalIgnoreCase)
                    .ToDictionary(k => k.Key, k => k.Value.OrderBy(p => p, StringComparer.Ordinal).ToList())),
                ["bsa"] = JObject.FromObject(bsa.OrderBy(k => k.Key, StringComparer.OrdinalIgnoreCase)
                    .ToDictionary(k => k.Key, k => k.Value.OrderBy(p => p, StringComparer.Ordinal).ToList())),
            },
        };

        var serializer = JsonSerializer.Create(JSONhandler<ModSetting>.GetMyMutagenJSONSettings());
        root["modSettings"] = new JArray(settings.ModSettings
            .OrderBy(m => m.DisplayName, StringComparer.OrdinalIgnoreCase)
            .Select(m => Normalize(JToken.FromObject(m, serializer), null)));

        root["inMemory"] = new JArray(mods.AllModSettings
            .OrderBy(v => v.DisplayName, StringComparer.OrdinalIgnoreCase)
            .Select(v => Normalize(new JObject
            {
                ["DisplayName"] = v.DisplayName,
                ["IsAutoGenerated"] = v.IsAutoGenerated,
                ["IsFaceGenOnlyEntry"] = v.IsFaceGenOnlyEntry,
                ["IsMugshotOnlyEntry"] = v.IsMugshotOnlyEntry,
                ["CorrespondingFolderPaths"] = new JArray(v.CorrespondingFolderPaths),
                ["CorrespondingModKeys"] = new JArray(v.CorrespondingModKeys.Select(k => k.FileName.String)),
                ["ResourceOnlyModKeys"] = new JArray(v.ResourceOnlyModKeys.Select(k => k.FileName.String)),
                ["NpcFormKeys"] = new JArray(v.NpcFormKeys.Select(k => k.ToString())),
                ["FaceGenOnlyNpcFormKeys"] = new JArray(v.FaceGenOnlyNpcFormKeys.Select(k => k.ToString())),
                ["AvailablePluginsForNpcs"] = new JObject(v.AvailablePluginsForNpcs.Select(kv =>
                    new JProperty(kv.Key.ToString(), new JArray(kv.Value.Select(k => k.FileName.String))))),
                ["MergeInDependencyRecords"] = v.MergeInDependencyRecords,
                ["HandleInjectedRecords"] = v.HandleInjectedRecords,
            }, null)));

        root["npcCatalogue"] = new JArray(harness.NpcSelectionBar.AllNpcs
            .OrderBy(n => n.NpcFormKey.ToString(), StringComparer.Ordinal)
            .Select(n => new JObject
            {
                ["FormKey"] = n.NpcFormKey.ToString(),
                ["DisplayName"] = n.DisplayName,
                ["IsInLoadOrder"] = n.IsInLoadOrder,
                ["SelectedAppearanceModName"] = n.SelectedAppearanceModName,
            }));

        root["caches"] = new JObject
        {
            ["CachedNonAppearanceMods"] = JObject.FromObject(settings.CachedNonAppearanceMods
                .OrderBy(k => k.Key, StringComparer.OrdinalIgnoreCase).ToDictionary(k => k.Key, k => k.Value)),
            ["CachedMissingMasterMods"] = Normalize(JToken.FromObject(settings.CachedMissingMasterMods, serializer), null),
        };
        root["dialogs"] = new JArray(dialogs.OrderBy(d => d, StringComparer.Ordinal));

        await File.WriteAllTextAsync(path, root.ToString(Formatting.Indented));
    }

    private static JToken Normalize(JToken token, string? propertyName)
    {
        switch (token)
        {
            case JObject obj:
                return new JObject(obj.Properties()
                    .OrderBy(p => p.Name, StringComparer.Ordinal)
                    .Select(p => new JProperty(p.Name, Normalize(p.Value, p.Name))));
            case JArray arr:
                var items = arr.Select(t => Normalize(t, null)).ToList();
                if (propertyName == null || !OrderedArrays.Contains(propertyName))
                {
                    items = items.OrderBy(t => t.ToString(Formatting.None), StringComparer.Ordinal).ToList();
                }
                return new JArray(items);
            default:
                return token.DeepClone();
        }
    }
}
