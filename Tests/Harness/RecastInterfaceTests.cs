using System.IO;
using FluentAssertions;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Skyrim;
using NPC_Plugin_Chooser_2.BackEnd;
using NPC_Plugin_Chooser_2.Models;
using NPC_Plugin_Chooser_2.Tests.Integration;
using NPC_Plugin_Chooser_2.Tests.TestSupport;
using Xunit;

namespace NPC_Plugin_Chooser_2.Tests.Harness;

/// <summary>
/// <see cref="RecastInterface"/> — emits the Recast patch TOML. Driven like
/// <see cref="SkyPatcherInterfaceTests"/>: an Invalid provider (no game) with an in-memory output
/// plugin, writing into a <see cref="TempDir"/>.
/// </summary>
[Collection(NpcChooserIntegrationCollection.Name)]
public class RecastInterfaceTests
{
    private static readonly FormKey Lydia = FormKey.Factory("0A2C8E:Skyrim.esm");
    private static readonly FormKey Faendal = FormKey.Factory("013480:Skyrim.esm");
    private static readonly FormKey DawnguardNpc = FormKey.Factory("002B6C:Dawnguard.esm");
    private static readonly FormKey SurrogateA = FormKey.Factory("000801:NPCTest.esp");
    private static readonly FormKey SurrogateB = FormKey.Factory("000802:NPCTest.esp");
    private static readonly FormKey SurrogateC = FormKey.Factory("000803:NPCTest.esp");

    private static RecastInterface NewInterface(int priority = 1000)
    {
        var env = NpcChooserTestEnvironment.Invalid();
        env.OutputMod = new SkyrimMod(ModKey.FromName("NPCTest", ModType.Plugin), SkyrimRelease.SkyrimSE);
        return new RecastInterface(env, new Settings { RecastPatchPriority = priority });
    }

    private static string TomlPath(string root, string outputModName = "NPCTest") =>
        Path.Combine(root, "SKSE", "Plugins", "Recast", "Patches", "NPC Plugin Chooser", outputModName + ".toml");

    // ── Selector ──────────────────────────────────────────────────────────────

    [Theory]
    [InlineData("0A2C8E:Skyrim.esm", "0x000A2C8E~Skyrim.esm")]
    [InlineData("000801:NPC Output.esp", "0x00000801~NPC Output.esp")]
    [InlineData("000801:NPC Output.esl", "0x00000801~NPC Output.esl")]
    [InlineData("FFFFFF:Big.esp", "0x00FFFFFF~Big.esp")]
    public void Selector_IsLocalIdTildePlugin(string formKey, string expected)
    {
        RecastInterface.FormatSelector(FormKey.Factory(formKey)).Should().Be(expected);
    }

    [Fact]
    public void Quote_EscapesBackslashQuoteAndControlCharacters()
    {
        RecastInterface.Quote("a\\b\"c\td\u0001").Should().Be("\"a\\\\b\\\"c\\td\\u0001\"");
    }

    // ── Write ─────────────────────────────────────────────────────────────────

    [Fact]
    public void Write_ProducesManifestAndSortedBlocks()
    {
        using var tmp = new TempDir("recast");
        var recast = NewInterface(priority: 1234);
        recast.AddFace(Lydia, SurrogateA, "Lydia");
        recast.AddFace(DawnguardNpc, SurrogateC);
        recast.AddFace(Faendal, SurrogateB, "Faendal");

        recast.WriteToml(tmp.Path).Should().BeTrue();

        File.ReadAllText(TomlPath(tmp.Path)).Should().Be(
            "# Generated by NPC Plugin Chooser 2. Do not edit: it is regenerated every run.\n" +
            "[manifest]\n" +
            "name = \"NPC Plugin Chooser 2\"\n" +
            "priority = 1234\n" +
            "api_version = 1\n" +
            "\n" +
            "[[npcs]]\n" +
            "target = \"0x00002B6C~Dawnguard.esm\"\n" +
            "face = \"0x00000803~NPCTest.esp\"\n" +
            "\n" +
            "# Faendal\n" +
            "[[npcs]]\n" +
            "target = \"0x00013480~Skyrim.esm\"\n" +
            "face = \"0x00000802~NPCTest.esp\"\n" +
            "\n" +
            "# Lydia\n" +
            "[[npcs]]\n" +
            "target = \"0x000A2C8E~Skyrim.esm\"\n" +
            "face = \"0x00000801~NPCTest.esp\"\n");
    }

    [Fact]
    public void Write_IsUtf8WithoutBomAndLfOnly()
    {
        using var tmp = new TempDir("recast");
        var recast = NewInterface();
        recast.AddFace(Lydia, SurrogateA, "Lýdia");

        recast.WriteToml(tmp.Path).Should().BeTrue();

        var bytes = File.ReadAllBytes(TomlPath(tmp.Path));
        bytes.Take(3).Should().NotEqual(new byte[] { 0xEF, 0xBB, 0xBF });
        bytes.Should().NotContain((byte)'\r');
        System.Text.Encoding.UTF8.GetString(bytes).Should().Contain("# Lýdia\n");
    }

    [Fact]
    public void Write_AppliesSplitRemapToBothSelectors()
    {
        using var tmp = new TempDir("recast");
        var recast = NewInterface();
        recast.AddFace(Lydia, SurrogateA);

        var moved = FormKey.Factory("000801:NPCTest_2.esp");
        recast.WriteToml(tmp.Path, new Dictionary<FormKey, FormKey> { [SurrogateA] = moved }).Should().BeTrue();

        File.ReadAllText(TomlPath(tmp.Path)).Should().Contain("face = \"0x00000801~NPCTest_2.esp\"")
            .And.NotContain("~NPCTest.esp");
    }

    [Fact]
    public void Write_CommentWithLineBreaksStaysOneLine()
    {
        using var tmp = new TempDir("recast");
        var recast = NewInterface();
        recast.AddFace(Lydia, SurrogateA, "Lydia\r\n[[npcs]]");

        recast.WriteToml(tmp.Path).Should().BeTrue();

        var text = File.ReadAllText(TomlPath(tmp.Path));
        text.Should().Contain("# Lydia  [[npcs]]\n");
        text.Split("\n[[npcs]]\n").Should().HaveCount(2, "the comment must not open a second block");
    }

    [Fact]
    public void AddFace_SecondCallForTheSameTargetReplacesTheFirst()
    {
        using var tmp = new TempDir("recast");
        var recast = NewInterface();
        recast.AddFace(Lydia, SurrogateA);
        recast.AddFace(Lydia, SurrogateB);

        recast.EnumerateDirectiveFormKeys().Should().Equal(SurrogateB);
        recast.WriteToml(tmp.Path).Should().BeTrue();
        File.ReadAllText(TomlPath(tmp.Path)).Should().Contain("0x00000802~").And.NotContain("0x00000801~");
    }

    [Fact]
    public void AddFace_IgnoresNullFormKeys()
    {
        var recast = NewInterface();
        recast.AddFace(FormKey.Null, SurrogateA);
        recast.AddFace(Lydia, FormKey.Null);
        recast.HasEntries.Should().BeFalse();
    }

    [Fact]
    public void Write_WithNoEntriesDeletesTheOldFileAndWritesNothing()
    {
        using var tmp = new TempDir("recast");
        var path = TomlPath(tmp.Path);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, "stale");

        NewInterface().WriteToml(tmp.Path).Should().BeTrue();

        File.Exists(path).Should().BeFalse();
    }

    // ── Reinitialize ──────────────────────────────────────────────────────────

    [Fact]
    public void Reinitialize_ClearsQueueAndOwnFileOnly()
    {
        using var tmp = new TempDir("recast");
        var own = TomlPath(tmp.Path);
        var sibling = TomlPath(tmp.Path, "NPCTest_2");
        Directory.CreateDirectory(Path.GetDirectoryName(own)!);
        File.WriteAllText(own, "stale");
        File.WriteAllText(sibling, "stale");

        var recast = NewInterface();
        recast.AddFace(Lydia, SurrogateA);
        recast.Reinitialize(tmp.Path);

        recast.HasEntries.Should().BeFalse();
        File.Exists(own).Should().BeFalse();
        File.Exists(sibling).Should().BeTrue();
    }

    [Fact]
    public void Reinitialize_ClearAll_SweepsEveryGeneratedTomlButNothingElse()
    {
        using var tmp = new TempDir("recast");
        var own = TomlPath(tmp.Path);
        var sibling = TomlPath(tmp.Path, "NPCTest_2");
        var dir = Path.GetDirectoryName(own)!;
        Directory.CreateDirectory(dir);
        File.WriteAllText(own, "stale");
        File.WriteAllText(sibling, "stale");
        var notes = Path.Combine(dir, "readme.txt");
        File.WriteAllText(notes, "keep");
        var thirdParty = Path.Combine(tmp.Path, "SKSE", "Plugins", "Recast", "Patches", "OtherPack.toml");
        File.WriteAllText(thirdParty, "keep");

        NewInterface().Reinitialize(tmp.Path, clearAllGeneratedTomls: true);

        File.Exists(own).Should().BeFalse();
        File.Exists(sibling).Should().BeFalse();
        File.Exists(notes).Should().BeTrue();
        File.Exists(thirdParty).Should().BeTrue("only NPC2's own subfolder is NPC2's to sweep");
    }
}
