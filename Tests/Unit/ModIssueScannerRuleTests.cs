    // --- Per-plugin dark-face grading (multi-plugin mods, cache v9) ---

    private static Npc AddParts(Npc npc, params FormKey[] headParts)
    {
        foreach (var hp in headParts) npc.HeadParts.Add(hp.ToLink<IHeadPartGetter>());
        return npc;
    }

    [Fact]
    public void DarkFaceSignature_SameRecordContent_MatchesAcrossPlugins()
    {
        // The WICO shape of things: the same NPC override in two of the mod's
        // plugins. Identical content must collapse to ONE verdict row.
        var modA = TestSupport.MutagenFixtures.NewMod("WICO - Immersive People.esp");
        var modB = TestSupport.MutagenFixtures.NewMod("WICO - USSEP Compatible Patch.esp");
        var race = TestSupport.MutagenFixtures.NewRace(modA, "NordRace");
        var hp1 = FormKey.Factory("000AAA:Parts.esp");
        var hp2 = FormKey.Factory("000BBB:Parts.esp");

        var a = AddParts(TestSupport.MutagenFixtures.NewNpc(modA, race: race), hp1, hp2);
        var b = AddParts(TestSupport.MutagenFixtures.NewNpc(modB, race: race), hp1, hp2);

        Assert.Equal(ModIssueScanner.NpcDarkFaceSignature(a), ModIssueScanner.NpcDarkFaceSignature(b));
    }

    [Fact]
    public void DarkFaceSignature_DiscriminatesEveryAnalyzerInput()
    {
        var mod = TestSupport.MutagenFixtures.NewMod("Test.esp");
        var race = TestSupport.MutagenFixtures.NewRace(mod, "NordRace");
        var race2 = TestSupport.MutagenFixtures.NewRace(mod, "DarkElfRace");
        var hp1 = FormKey.Factory("000AAA:Parts.esp");
        var hp2 = FormKey.Factory("000BBB:Parts.esp");

        var baseline = AddParts(TestSupport.MutagenFixtures.NewNpc(mod, race: race), hp1, hp2);
        string baseSig = ModIssueScanner.NpcDarkFaceSignature(baseline);

        // Head-part ORDER is significant: singular slots are first-listed-wins.
        Assert.NotEqual(baseSig, ModIssueScanner.NpcDarkFaceSignature(
            AddParts(TestSupport.MutagenFixtures.NewNpc(mod, race: race), hp2, hp1)));
        Assert.NotEqual(baseSig, ModIssueScanner.NpcDarkFaceSignature(
            AddParts(TestSupport.MutagenFixtures.NewNpc(mod, race: race), hp1)));
        Assert.NotEqual(baseSig, ModIssueScanner.NpcDarkFaceSignature(
            AddParts(TestSupport.MutagenFixtures.NewNpc(mod, race: race2), hp1, hp2)));
        Assert.NotEqual(baseSig, ModIssueScanner.NpcDarkFaceSignature(
            AddParts(TestSupport.MutagenFixtures.NewNpc(mod, female: true, race: race), hp1, hp2)));
        Assert.NotEqual(baseSig, ModIssueScanner.NpcDarkFaceSignature(
            AddParts(TestSupport.MutagenFixtures.NewNpc(mod, traitsTemplate: true, template: baseline, race: race),
                hp1, hp2)));
    }

    [Fact]
    public void GroupPluginRecords_IdenticalCollapseWithJoinedLabel_DifferingStaySeparate()
    {
        var modA = TestSupport.MutagenFixtures.NewMod("A.esp");
        var modB = TestSupport.MutagenFixtures.NewMod("B.esp");
        var race = TestSupport.MutagenFixtures.NewRace(modA, "NordRace");
        var hp1 = FormKey.Factory("000AAA:Parts.esp");
        var hp2 = FormKey.Factory("000BBB:Parts.esp");

        // Identical records in both plugins -> one entry labeled with both carriers.
        var sameA = AddParts(TestSupport.MutagenFixtures.NewNpc(modA, race: race), hp1);
        var sameB = AddParts(TestSupport.MutagenFixtures.NewNpc(modB, race: race), hp1);
        var collapsed = ModIssueScanner.GroupPluginRecordsBySignature(new[]
        {
            (modA.ModKey, (INpcGetter)sameA),
            (modB.ModKey, (INpcGetter)sameB),
        });
        Assert.Single(collapsed);
        Assert.Equal("A.esp, B.esp", collapsed[0].Label);
        Assert.Same(sameA, collapsed[0].Record); // first carrier's record represents the group
        // Individual filenames travel alongside the display join (filenames can
        // legally contain commas, so consumers must never split the label).
        Assert.Equal(new[] { "A.esp", "B.esp" }, collapsed[0].Plugins);

        // Differing records -> per-plugin entries, plugin order preserved.
        var diffB = AddParts(TestSupport.MutagenFixtures.NewNpc(modB, race: race), hp1, hp2);
        var split = ModIssueScanner.GroupPluginRecordsBySignature(new[]
        {
            (modA.ModKey, (INpcGetter)sameA),
            (modB.ModKey, (INpcGetter)diffB),
        });
        Assert.Equal(2, split.Count);
        Assert.Equal("A.esp", split[0].Label);
        Assert.Equal("B.esp", split[1].Label);
    }

