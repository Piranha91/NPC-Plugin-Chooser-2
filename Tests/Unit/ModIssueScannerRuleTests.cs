    /// <summary>Eligibility now includes an installed-content check, so the folder
    /// (when present) must really exist with content for the positive cases.</summary>
    private static ModSetting MakeMod(bool autoGenerated = false, bool folders = true, bool npcs = true,
        string? folderPath = null)
    {
        var mod = new ModSetting
        {
            DisplayName = "Test Mod",
            IsAutoGenerated = autoGenerated,
        };
        if (folders) mod.CorrespondingFolderPaths.Add(folderPath ?? @"C:\Mods\Test");
        if (npcs) mod.NpcFormKeys.Add(FormKey.Factory("000ABC:Test.esp"));
        return mod;
    }

    private static string MakeContentFolder(TestSupport.TempDir dir)
    {
        System.IO.File.WriteAllText(System.IO.Path.Combine(dir.Path, "dummy.esp"), "x");
        return dir.Path;
    }

    [Fact]
    public void Eligibility_RequiresFoldersAndNpcs_ExcludesAutoGenerated()
