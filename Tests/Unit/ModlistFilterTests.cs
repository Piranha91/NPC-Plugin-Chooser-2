using System;
using System.Collections.Generic;
using FluentAssertions;
using NPC_Plugin_Chooser_2.Models;
using NPC_Plugin_Chooser_2.View_Models;
using Xunit;

namespace NPC_Plugin_Chooser_2.Tests.Unit;

/// <summary>
/// <c>VM_Mods.IsHiddenByModlistFilter</c>: which persisted mod entries the active-mods (modlist.txt)
/// filter hides. The filter used to apply only to the folder scan, so mods registered before it was
/// turned on stayed visible even when disabled in the mod manager.
/// </summary>
public class ModlistFilterTests
{
    private const string ModsFolder = @"C:\MO2\mods";

    private static readonly HashSet<string> Enabled =
        new(StringComparer.OrdinalIgnoreCase) { "Enabled Mod" };

    private static ModSetting Mod(params string[] folders) =>
        new() { DisplayName = "Test", CorrespondingFolderPaths = new List<string>(folders) };

    [Fact]
    public void DisabledFolderUnderModsFolder_IsHidden() =>
        VM_Mods.IsHiddenByModlistFilter(Mod(@"C:\MO2\mods\Disabled Mod"), ModsFolder, Enabled)
            .Should().BeTrue();

    [Fact]
    public void EnabledFolder_IsKept_CaseInsensitively() =>
        VM_Mods.IsHiddenByModlistFilter(Mod(@"C:\MO2\mods\ENABLED MOD\"), ModsFolder + @"\", Enabled)
            .Should().BeFalse();

    [Fact]
    public void AnyEnabledFolder_KeepsAMultiFolderEntry() =>
        VM_Mods.IsHiddenByModlistFilter(Mod(@"C:\MO2\mods\Disabled Mod", @"C:\MO2\mods\Enabled Mod"), ModsFolder, Enabled)
            .Should().BeFalse();

    [Fact]
    public void FolderOutsideModsFolder_IsKept() =>
        VM_Mods.IsHiddenByModlistFilter(Mod(@"D:\Elsewhere\Disabled Mod"), ModsFolder, Enabled)
            .Should().BeFalse("the modlist can only speak for folders directly inside the Mods folder");

    [Fact]
    public void AutoGeneratedOrFolderlessEntries_AreKept()
    {
        VM_Mods.IsHiddenByModlistFilter(new ModSetting { DisplayName = "Base Game", IsAutoGenerated = true }, ModsFolder, Enabled)
            .Should().BeFalse();
        VM_Mods.IsHiddenByModlistFilter(Mod(), ModsFolder, Enabled).Should().BeFalse();
    }
}
