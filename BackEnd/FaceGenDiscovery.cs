namespace NPC_Plugin_Chooser_2.BackEnd;

/// <summary>
/// One entry the FaceGen path cache is built for — a mod folder, a synthetic Base Game / Creation Club
/// entry, or an existing <c>VM_ModSetting</c> being refreshed — as plain data, so discovery can enumerate
/// folders, plugins and their archives without constructing temporary view models.
/// </summary>
internal sealed record DiscoveryCandidate(
    string DisplayName,
    IReadOnlyList<string> FolderPaths,
    IReadOnlyList<ModKey> ModKeys,
    bool IsAutoGenerated);

/// <summary>Outcome of the cheap folder-metadata probe of one archive.</summary>
internal enum ArchiveProbeOutcome
{
    /// <summary>The archive's folder table was fully validated and contains no FaceGen folder.</summary>
    Absent,
    /// <summary>The archive's folder table was fully validated and lists at least one FaceGen folder.</summary>
    Present,
    /// <summary>The metadata could not be read or validated; the caller must use the full reader.</summary>
    Inconclusive,
}

internal readonly record struct ArchiveFolderProbe(
    ArchiveProbeOutcome Outcome,
    IReadOnlyList<string> FaceGenFolders,
    string? InconclusiveReason)
{
    public static ArchiveFolderProbe Inconclusive(string reason) =>
        new(ArchiveProbeOutcome.Inconclusive, Array.Empty<string>(), reason);
}

/// <summary>
/// Targeted FaceGen discovery for the mod-population pipeline. It answers "does this folder or archive
/// supply FaceGen, and which files?" while reading only the FaceGen parts of the inputs:
/// <list type="bullet">
///   <item><b>Loose files:</b> enumerates only <c>meshes/actors/character/facegendata/facegeom</c> (<c>*.nif</c>)
///     and <c>textures/actors/character/facegendata/facetint</c> (<c>*.dds</c>) below each folder, instead of
///     every mesh and texture the mod ships.</item>
///   <item><b>Archives:</b> reads the BSA's header and folder table (folder names and per-folder file counts —
///     not the file-name table, not file data) to prove whether any FaceGen folder exists, then asks
///     Mutagen's reader for the files of only those folders. Anything the probe cannot validate falls back to
///     the full Mutagen enumeration the original implementation used.</item>
/// </list>
/// Output strings are byte-for-byte the ones the original implementation produced, so every consumer
/// (<c>FaceGenScanner</c>, <c>VM_ModSetting.FaceGenExists</c>) sees identical data.
///
/// <para>This answers FaceGen questions only. Rendering and patching keep resolving every other asset
/// through <see cref="BsaHandler"/>'s own on-demand archive indexing, which this class does not touch.</para>
/// </summary>
internal static class FaceGenDiscovery
{
    /// <summary>
    /// Benchmark/oracle switch: when true, <c>VM_Mods</c> runs the original broad FaceGen path cache
    /// instead of the targeted one. Never set by the app; the discovery benchmark and the equivalence
    /// tests set it to compare both implementations over the same inputs.
    /// </summary>
    internal static bool UseLegacyImplementation;

    private static readonly string[] MeshSegments = { "actors", "character", "facegendata", "facegeom" };
    private static readonly string[] TextureSegments = { "actors", "character", "facegendata", "facetint" };

    // Archive paths the original implementation kept: lower-cased, forward slashes, under facegendata.
    private const string MeshFaceGenDataPrefix = "meshes/actors/character/facegendata/";
    private const string TextureFaceGenDataPrefix = "textures/actors/character/facegendata/";
    // The same roots as archive folder names (Mutagen normalizes folder separators to '\').
    private const string MeshFaceGenDataFolder = @"meshes\actors\character\facegendata";
    private const string TextureFaceGenDataFolder = @"textures\actors\character\facegendata";

    // ---------------------------------------------------------------------------------------------
    // Loose files
    // ---------------------------------------------------------------------------------------------

    /// <summary>
    /// Loose FaceGen paths per folder, keyed by the folder string as given (consumers look entries up by
    /// their own <c>CorrespondingFolderPaths</c> strings). Values are paths relative to the folder with
    /// forward slashes, e.g. <c>Meshes/actors/character/FaceGenData/FaceGeom/Skyrim.esm/00013BA1.nif</c> — the
    /// first segment spelled <c>Meshes</c>/<c>Textures</c> and the rest in on-disk casing, exactly as the original
    /// recursive enumeration produced them. Folders with no FaceGen are omitted. Several references to the same
    /// physical folder (different spelling, trailing separator) are enumerated once.
    /// </summary>
    internal static Dictionary<string, HashSet<string>> DiscoverLooseFaceGen(IEnumerable<string> folderPaths)
    {
        var result = new Dictionary<string, HashSet<string>>(StringComparer.OrdinalIgnoreCase);
        var byPhysicalFolder = new Dictionary<string, HashSet<string>?>(StringComparer.OrdinalIgnoreCase);
        var seenSpellings = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var folder in folderPaths)
        {
            if (string.IsNullOrEmpty(folder) || !seenSpellings.Add(folder)) continue;
            if (!Directory.Exists(folder)) continue;

            var physical = NormalizeFolder(folder);
            if (byPhysicalFolder.TryGetValue(physical, out var alreadyScanned))
            {
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.LooseDuplicateFolderReferences);
                if (alreadyScanned != null)
                {
                    result[folder] = new HashSet<string>(alreadyScanned, StringComparer.OrdinalIgnoreCase);
                }
                continue;
            }

            var files = EnumerateLooseFaceGen(folder);
            byPhysicalFolder[physical] = files.Count > 0 ? files : null;
            if (files.Count > 0)
            {
                result[folder] = files;
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.LoosePathsRetained, files.Count);
            }
        }

        return result;
    }

    /// <summary>Loose FaceGen below one folder (see <see cref="DiscoverLooseFaceGen"/> for the path format).</summary>
    internal static HashSet<string> EnumerateLooseFaceGen(string folder)
    {
        DiscoveryMetrics.Add(DiscoveryMetrics.Counter.LooseFoldersScanned);
        var files = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        long candidates = 0;

        // Textures before Meshes, as the original enumeration ran: the set's insertion order decides which
        // spelling of a plugin folder FaceGenScanner sees first when a mod's facetint and facegeom folders
        // differ only in case (e.g. "Glenmoril.esm" vs "glenmoril.esm"), and that spelling ends up in the
        // FaceGen-only FormKeys that are persisted and shown.
        foreach (var (topFolder, segments, pattern) in new[]
                 {
                     ("Textures", TextureSegments, "*.dds"),
                     ("Meshes", MeshSegments, "*.nif"),
                 })
        {
            var top = Path.Combine(folder, topFolder);
            if (!Directory.Exists(top)) continue;

            foreach (var root in ResolveSubdirectories(top, segments))
            {
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.LooseRootsEnumerated);
                // Recursive below the FaceGen root, like the original: nested layouts (backup folders inside a
                // plugin folder, files directly in facegeom) are kept here and judged by the consumers.
                foreach (var file in Directory.EnumerateFiles(root, pattern, SearchOption.AllDirectories))
                {
                    candidates++;
                    files.Add(Path.GetRelativePath(folder, file).Replace('\\', '/'));
                }
            }
        }

        DiscoveryMetrics.Add(DiscoveryMetrics.Counter.LooseCandidatePaths, candidates);
        return files;
    }

    /// <summary>
    /// True if any of <paramref name="folderPaths"/> holds at least one <c>*.dds</c> anywhere under
    /// <c>Textures</c> or <c>*.nif</c> anywhere under <c>Meshes</c> — FaceGen or not. This is the question the
    /// single-mod refresh historically asked of the broad cache ("is the cache non-empty?") when deciding
    /// whether a plugin-less mod survives as a FaceGen-only entry. It is kept as its own, early-exiting probe so
    /// narrowing the FaceGen cache does not silently change that classification.
    /// </summary>
    internal static bool AnyLooseMeshOrTexture(IEnumerable<string> folderPaths)
    {
        foreach (var folder in folderPaths.Distinct(StringComparer.OrdinalIgnoreCase))
        {
            if (string.IsNullOrEmpty(folder) || !Directory.Exists(folder)) continue;
            var textures = Path.Combine(folder, "Textures");
            if (Directory.Exists(textures) &&
                Directory.EnumerateFiles(textures, "*.dds", SearchOption.AllDirectories).Any()) return true;
            var meshes = Path.Combine(folder, "Meshes");
            if (Directory.Exists(meshes) &&
                Directory.EnumerateFiles(meshes, "*.nif", SearchOption.AllDirectories).Any()) return true;
        }
        return false;
    }

    /// <summary>
    /// Resolves <paramref name="segments"/> below <paramref name="root"/> one level at a time, matching each
    /// name case-insensitively and returning the on-disk spelling (so relative paths keep the casing the
    /// original enumeration reported). Normally yields zero or one directory; a case-sensitive directory could
    /// hold several spellings, and all of them are returned.
    /// </summary>
    private static IEnumerable<string> ResolveSubdirectories(string root, IReadOnlyList<string> segments)
    {
        IEnumerable<string> current = new[] { root };
        foreach (var segment in segments)
        {
            var next = new List<string>();
            foreach (var dir in current)
            {
                next.AddRange(Directory.EnumerateDirectories(dir, segment, SearchOption.TopDirectoryOnly));
            }
            if (next.Count == 0) return Array.Empty<string>();
            current = next;
        }
        return current;
    }

    private static string NormalizeFolder(string folder) =>
        Path.GetFullPath(folder).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);

    // ---------------------------------------------------------------------------------------------
    // Archives
    // ---------------------------------------------------------------------------------------------

    private sealed record CachedArchiveListing(long Length, DateTime LastWriteTimeUtc, HashSet<string> Paths);

    /// <summary>
    /// In-process FaceGen listings of archives already read, invalidated by the same rule the analysis cache
    /// uses for archives (<c>FileSnapshot</c>: file size + last-write time). Serves repeat discovery within a
    /// session (single-mod refresh, adding a mod, Refresh All) without re-reading unchanged archives.
    /// </summary>
    private static readonly ConcurrentDictionary<string, CachedArchiveListing> ArchiveListings =
        new(StringComparer.OrdinalIgnoreCase);

    internal static void ClearArchiveListingCache() => ArchiveListings.Clear();

    /// <summary>
    /// The FaceGen paths inside one archive, in the original format (lower case, forward slashes, everything
    /// under <c>meshes|textures/actors/character/facegendata/</c>). Uses the folder-metadata probe and reads
    /// file lists only for FaceGen folders; falls back to enumerating every file through
    /// <paramref name="openReader"/> when the probe is inconclusive or Mutagen cannot address a probed folder.
    /// </summary>
    /// <param name="openReader">Opens (or returns the shared cached) Mutagen reader for the archive —
    /// <see cref="BsaHandler.OpenBsaArchiveReaders"/> in production, so reader sharing and reference counting
    /// stay with the handler. May return null when the archive cannot be opened.</param>
    internal static HashSet<string> GetArchiveFaceGenPaths(string bsaPath, Func<string, IArchiveReader?> openReader)
    {
        FileInfo info;
        try
        {
            info = new FileInfo(bsaPath);
        }
        catch
        {
            return ReadAllFaceGenEntries(bsaPath, openReader);
        }

        if (info.Exists &&
            ArchiveListings.TryGetValue(bsaPath, out var cached) &&
            cached.Length == info.Length && cached.LastWriteTimeUtc == info.LastWriteTimeUtc)
        {
            DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchiveListingCacheHits);
            return cached.Paths;
        }

        var paths = ReadFaceGenPaths(bsaPath, openReader);
        if (info.Exists)
        {
            ArchiveListings[bsaPath] = new CachedArchiveListing(info.Length, info.LastWriteTimeUtc, paths);
        }
        return paths;
    }

    private static HashSet<string> ReadFaceGenPaths(string bsaPath, Func<string, IArchiveReader?> openReader)
    {
        var probe = ProbeArchiveFolders(bsaPath);
        DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivesProbed);
        switch (probe.Outcome)
        {
            case ArchiveProbeOutcome.Absent:
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivesProbeAbsent);
                return new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            case ArchiveProbeOutcome.Present:
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivesProbePresent);
                var reader = openReader(bsaPath);
                if (reader == null) return new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                var fromFolders = TryReadFaceGenFolders(reader, probe.FaceGenFolders);
                if (fromFolders != null) return fromFolders;
                // Mutagen could not address a folder the probe listed: trust the full reader instead.
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivesProbeInconclusive);
                return ReadAllFaceGenEntries(reader);

            default:
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivesProbeInconclusive);
                return ReadAllFaceGenEntries(bsaPath, openReader);
        }
    }

    private static HashSet<string>? TryReadFaceGenFolders(IArchiveReader reader, IReadOnlyList<string> folders)
    {
        var paths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        long entries = 0;
        try
        {
            foreach (var folderName in folders)
            {
                if (!reader.TryGetFolder(folderName, out var folder)) return null;
                DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchiveFoldersRead);
                foreach (var file in folder.Files)
                {
                    entries++;
                    AddIfFaceGen(paths, file.Path);
                }
            }
        }
        catch (Exception)
        {
            // e.g. Mutagen's folder dictionary rejecting a folder name it considers duplicate.
            return null;
        }
        finally
        {
            DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchiveFileEntriesEnumerated, entries);
        }
        DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivePathsRetained, paths.Count);
        return paths;
    }

    private static HashSet<string> ReadAllFaceGenEntries(string bsaPath, Func<string, IArchiveReader?> openReader)
    {
        var reader = openReader(bsaPath);
        return reader == null ? new HashSet<string>(StringComparer.OrdinalIgnoreCase) : ReadAllFaceGenEntries(reader);
    }

    /// <summary>The original full enumeration: every file record of the archive, filtered afterwards.</summary>
    private static HashSet<string> ReadAllFaceGenEntries(IArchiveReader reader)
    {
        var paths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        long entries = 0;
        DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivesFullyIndexed);
        foreach (var file in reader.Files)
        {
            entries++;
            AddIfFaceGen(paths, file.Path);
        }
        DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchiveFileEntriesEnumerated, entries);
        DiscoveryMetrics.Add(DiscoveryMetrics.Counter.ArchivePathsRetained, paths.Count);
        return paths;
    }

    private static void AddIfFaceGen(HashSet<string> paths, string archivePath)
    {
        string path = archivePath.ToLowerInvariant().Replace('\\', '/');
        if (path.StartsWith(MeshFaceGenDataPrefix) || path.StartsWith(TextureFaceGenDataPrefix))
        {
            paths.Add(path);
        }
    }

    // ---------------------------------------------------------------------------------------------
    // Folder-metadata probe
    // ---------------------------------------------------------------------------------------------

    private const int BsaHeaderLength = 0x24;
    private const uint ArchiveFlagHasFolderNames = 0x1;
    private const uint ArchiveFlagHasFileNames = 0x2;
    private const int FileRecordLength = 0x10;

    /// <summary>
    /// Reads a Skyrim BSA's header and folder table — the 36-byte header, the folder records and the
    /// per-folder name/file-record blocks — and reports whether any folder lies under
    /// <c>meshes|textures\actors\character\facegendata</c>. The file-name table and file data are never read.
    ///
    /// <para>Mutagen's public <see cref="IArchiveReader"/> offers no folder enumeration (only
    /// <see cref="IArchiveReader.TryGetFolder"/> by exact name, and <see cref="IArchiveReader.Files"/>, which
    /// materializes every entry), so this narrowly scoped reader exists only to answer the presence question.
    /// It is deliberately strict: it supports only the Skyrim LE/SE formats (versions 104/105) with folder and
    /// file names, and requires the folder table to reconcile exactly with the header (folder count, total file
    /// count, total folder-name length, every name NUL-terminated, no duplicate names). Any deviation —
    /// unsupported version, missing names, truncation, inconsistent totals, an I/O error — returns
    /// <see cref="ArchiveProbeOutcome.Inconclusive"/> so the caller uses the full reader; it never reports
    /// "absent" on metadata it could not validate.</para>
    ///
    /// <para>Folder names are decoded the way Mutagen 0.54 decodes them (Windows-1252 for SE, UTF-7 for LE,
    /// separators normalized to '\'), so they can be handed straight to <see cref="IArchiveReader.TryGetFolder"/>.</para>
    /// </summary>
    internal static ArchiveFolderProbe ProbeArchiveFolders(string bsaPath)
    {
        byte[]? rented = null;
        try
        {
            using var handle = File.OpenHandle(bsaPath, FileMode.Open, FileAccess.Read, FileShare.Read);
            long fileLength = RandomAccess.GetLength(handle);
            Span<byte> header = stackalloc byte[BsaHeaderLength];
            if (fileLength < BsaHeaderLength || RandomAccess.Read(handle, header, 0) != BsaHeaderLength)
                return ArchiveFolderProbe.Inconclusive("truncated header");
            if (header[0] != (byte)'B' || header[1] != (byte)'S' || header[2] != (byte)'A' || header[3] != 0)
                return ArchiveFolderProbe.Inconclusive("not a BSA");

            uint version = BinaryPrimitives.ReadUInt32LittleEndian(header[0x4..]);
            uint folderRecordOffset = BinaryPrimitives.ReadUInt32LittleEndian(header[0x8..]);
            uint archiveFlags = BinaryPrimitives.ReadUInt32LittleEndian(header[0xC..]);
            uint folderCount = BinaryPrimitives.ReadUInt32LittleEndian(header[0x10..]);
            uint fileCount = BinaryPrimitives.ReadUInt32LittleEndian(header[0x14..]);
            uint totalFolderNameLength = BinaryPrimitives.ReadUInt32LittleEndian(header[0x18..]);

            int folderRecordLength = version switch { 105 => 0x18, 104 => 0x10, _ => 0 };
            if (folderRecordLength == 0) return ArchiveFolderProbe.Inconclusive($"unsupported version {version}");
            if ((archiveFlags & ArchiveFlagHasFolderNames) == 0) return ArchiveFolderProbe.Inconclusive("no folder names");
            if ((archiveFlags & ArchiveFlagHasFileNames) == 0) return ArchiveFolderProbe.Inconclusive("no file names");
            if (folderRecordOffset < BsaHeaderLength) return ArchiveFolderProbe.Inconclusive("bad folder offset");

            // Folder records, then for each folder: length byte + NUL-terminated name + its file records.
            long directoryLength = (long)folderRecordLength * folderCount
                                   + folderCount + totalFolderNameLength
                                   + (long)FileRecordLength * fileCount;
            if (directoryLength > int.MaxValue || folderRecordOffset + directoryLength > fileLength)
                return ArchiveFolderProbe.Inconclusive("folder table exceeds file");

            rented = ArrayPool<byte>.Shared.Rent((int)directoryLength);
            var directory = rented.AsSpan(0, (int)directoryLength);
            if (RandomAccess.Read(handle, directory, folderRecordOffset) != directory.Length)
                return ArchiveFolderProbe.Inconclusive("short read");

            var encoding = version == 105 ? Windows1252.Value : Utf7;
            var faceGenFolders = new List<string>();
            var allNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            long fileTally = 0;
            long nameTally = 0;
            int cursor = folderRecordLength * (int)folderCount;
            for (int i = 0; i < folderCount; i++)
            {
                long folderFiles = BinaryPrimitives.ReadUInt32LittleEndian(directory[(i * folderRecordLength + 8)..]);
                fileTally += folderFiles;
                if (cursor >= directory.Length) return ArchiveFolderProbe.Inconclusive("truncated folder block");
                int nameLength = directory[cursor];
                if (nameLength == 0 || cursor + 1 + nameLength > directory.Length)
                    return ArchiveFolderProbe.Inconclusive("bad folder name length");
                var nameBytes = directory.Slice(cursor + 1, nameLength);
                if (nameBytes[^1] != 0) return ArchiveFolderProbe.Inconclusive("unterminated folder name");
                nameTally += nameLength;

                var name = encoding.GetString(nameBytes[..^1]).Replace('/', '\\');
                if (!allNames.Add(name)) return ArchiveFolderProbe.Inconclusive("duplicate folder name");
                if (IsFaceGenFolder(name)) faceGenFolders.Add(name);

                long next = cursor + 1L + nameLength + folderFiles * FileRecordLength;
                if (next > directory.Length) return ArchiveFolderProbe.Inconclusive("file records exceed folder table");
                cursor = (int)next;
            }

            if (fileTally != fileCount) return ArchiveFolderProbe.Inconclusive("file count mismatch");
            if (nameTally != totalFolderNameLength) return ArchiveFolderProbe.Inconclusive("folder name length mismatch");
            if (cursor != directory.Length) return ArchiveFolderProbe.Inconclusive("folder table length mismatch");

            return faceGenFolders.Count == 0
                ? new ArchiveFolderProbe(ArchiveProbeOutcome.Absent, Array.Empty<string>(), null)
                : new ArchiveFolderProbe(ArchiveProbeOutcome.Present, faceGenFolders, null);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException
                                       or NotSupportedException)
        {
            return ArchiveFolderProbe.Inconclusive(ex.GetType().Name + ": " + ex.Message);
        }
        finally
        {
            if (rented != null) ArrayPool<byte>.Shared.Return(rented);
        }
    }

    /// <summary>True for <c>facegendata</c> itself or any folder below it, under meshes or textures.</summary>
    internal static bool IsFaceGenFolder(string folderName) =>
        IsAtOrBelow(folderName, MeshFaceGenDataFolder) || IsAtOrBelow(folderName, TextureFaceGenDataFolder);

    private static bool IsAtOrBelow(string folderName, string root) =>
        folderName.StartsWith(root, StringComparison.OrdinalIgnoreCase) &&
        (folderName.Length == root.Length || folderName[root.Length] == '\\');

    private static readonly Lazy<Encoding> Windows1252 =
        new(() => CodePagesEncodingProvider.Instance.GetEncoding(1252) ?? Encoding.Latin1);

#pragma warning disable SYSLIB0001 // Mutagen 0.54 decodes pre-SE (v104) BSA names as UTF-7; match it.
    private static readonly Encoding Utf7 = Encoding.UTF7;
#pragma warning restore SYSLIB0001
}
