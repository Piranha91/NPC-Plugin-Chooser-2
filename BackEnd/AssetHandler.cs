    /// <summary>
    /// Returns a task that will complete when all scheduled asset operations have finished.
    /// </summary>
    public Task WhenAllTasks() => Task.WhenAll(_processedAssetTasks.Values);

    /// <summary>
    /// The main entry point for requesting an asset. It finds the asset's source (loose or BSA)
    /// and schedules a task to copy/extract it, including post-processing for NIF files.
    /// This operation is idempotent; subsequent requests for the same asset will return the existing task.
    /// </summary>
    /// <param name="relativePath">The asset's relative path (e.g., "textures\\actor.dds").</param>
    /// <param name="modSetting">The mod setting providing context for where to find the asset.</param>
    /// <param name="outputBasePath">The root output directory for the patch.</param>
    /// <param name="faceTintSubPath">The relative path of the face tint texture. Prevents mis-assignment of shared NPC face tints</param>
    /// <param name="explicitSourceAbsolutePath">
    /// Bypasses <see cref="FindAssetSource"/> and copies from this exact file. Used for the ladder's
    /// "winner" sources, whose bytes come from the merged Data view rather than any one mod's
    /// folders — everything downstream (dedup, destination claims, NIF post-processing) is
    /// unchanged, so a borrowed FaceGen is handled exactly like any other loose file.
    /// </param>
    /// <param name="isolationModTag">
    /// Marks this as an Include-As-New ISOLATION copy (see
    /// <see cref="ScheduleIncludeAsNewAssetIsolation"/>): post-copy analysis runs
    /// <see cref="PostProcessIsolatedCopy"/> on the DESTINATION file — isolating the NIF's internal
    /// texture references — instead of the standard source-side scan, which would schedule the
    /// mod's textures back onto their shared paths.
    /// </param>
    private Task RequestAssetCopyAsync(string relativePath, ModSetting modSetting, string outputBasePath, string faceTintSubPath, AssetRequestContext ctx, string? overrideDestinationRelativePath = null, string? explicitSourceAbsolutePath = null, string? isolationModTag = null)
    {
        // FIX: Create a composite key to uniquely identify an asset *within the context of its source mod*.
        // This prevents a failed lookup from one mod from blocking a successful lookup from another mod for the same relative path.

        string destRel = overrideDestinationRelativePath ?? relativePath;
        string cacheKey = $"{destRel}|{modSetting.DisplayName}";

        // Provenance is recorded on EVERY request (before the dedup below) so a file pulled in by
        // many NPCs lists them all; the physical copy still happens once via the task cache. No-op
        // unless the opt-in AssetProvenance diagnostic is enabled.
        AssetProvenanceDiag.RecordReference(destRel, modSetting.DisplayName, ctx);

        return _processedAssetTasks.GetOrAdd(cacheKey, _ => Task.Run(async () =>
        {
            await _nifProcessingSemaphore.WaitAsync();
            try
            {
                // Base-game-overwrite protection: unless the user opted in for this mod, assets
                // that would land on a base game / Creation Club asset path are not copied, so the
                // versions from the user's other installed mods (e.g. skin replacers) keep winning.
                // FaceGen is exempt (inherently per-NPC). This is a live path test independent of
                // the import-time scan that shows the checkbox, so a stale scan can never cause a
                // wrong copy. Skipping is reference-safe: records/NIFs keep their vanilla-relative
                // paths, which the game resolves from the load order as usual. The cheap pre-checks
                // here avoid triggering the one-time vanilla-index build for exempt requests.
                if (!modSetting.OverwriteBaseGameAssets &&
                    !string.Equals(ctx.Reason, "FaceGen", StringComparison.OrdinalIgnoreCase))
                {
                    var vanillaAssetPaths = await _bsaHandler.GetVanillaAssetPathsAsync();
                    if (ShouldSkipAsBaseGameOverwrite(destRel, ctx.Reason,
                            modSetting.OverwriteBaseGameAssets, vanillaAssetPaths))
                    {
                        AssetProvenanceDiag.RecordSource(destRel, modSetting.DisplayName,
                            AssetProvenanceDiag.SkippedBaseGameOverwriteKind, null);
                        return; // Task completes as a no-op, mirroring the NotFound branch below.
                    }
                }

                var (sourceType, sourcePath, bsaPath) =
                    explicitSourceAbsolutePath != null && File.Exists(explicitSourceAbsolutePath)
                        ? (AssetSourceType.LooseFile, explicitSourceAbsolutePath, string.Empty)
                        : FindAssetSource(relativePath, modSetting);
                string destPath = Path.Combine(outputBasePath, relativePath);
                if (overrideDestinationRelativePath != null)
                {
                    destPath = Path.Combine(outputBasePath, overrideDestinationRelativePath);
                }

                // Single-writer-per-destination guard (see _claimedDestinations). Claimed only once
                // a real source is found, so a mod that lacks the file can never block one that has
                // it. Losing the claim means another mod is already producing this exact file, so
                // this task skips its copy AND the NIF post-processing (which would otherwise parse
                // the destination while the winner is still writing it).
                DestinationClaim? claim = null;
                if (sourceType != AssetSourceType.NotFound)
                {
                    claim = _claimedDestinations.GetOrAdd(destPath, _ => new DestinationClaim
                    {
                        OwnerCacheKey = cacheKey,
                        OwnerIsAutoGenerated = modSetting.IsAutoGenerated
                    });
                    bool mayWrite;
                    lock (claim)
                    {
                        if (claim.OwnerCacheKey == cacheKey)
                        {
                            mayWrite = true; // This task created the claim.
                        }
                        else if (claim.OwnerIsAutoGenerated && !modSetting.IsAutoGenerated)
                        {
                            // Dethrone the synthetic entry; the ownership re-check under WriteLock
                            // below keeps its write (if still pending) from landing after ours.
                            claim.OwnerCacheKey = cacheKey;
                            claim.OwnerIsAutoGenerated = false;
                            mayWrite = true;
                        }
                        else
                        {
                            mayWrite = false;
                        }
                    }

                    if (!mayWrite)
                    {
                        AssetProvenanceDiag.RecordSource(destRel, modSetting.DisplayName,
                            AssetProvenanceDiag.SkippedDuplicateDestinationKind, null);
                        return;
                    }

                    await claim.WriteLock.WaitAsync();
                    bool stillOwner;
                    lock (claim)
                    {
                        stillOwner = claim.OwnerCacheKey == cacheKey;
                    }
                    if (!stillOwner)
                    {
                        // Dethroned while queued for the lock (a real mod took over from a
                        // synthetic entry); the new owner writes after us or already has.
                        claim.WriteLock.Release();
                        AssetProvenanceDiag.RecordSource(destRel, modSetting.DisplayName,
                            AssetProvenanceDiag.SkippedDuplicateDestinationKind, null);
                        return;
                    }
                }

                try
                {
                    // Record where the bytes came from once per unique file+mod (the task runs once per cacheKey).
                    AssetProvenanceDiag.RecordSource(destRel, modSetting.DisplayName, sourceType.ToString(),
                        sourceType == AssetSourceType.BsaFile ? bsaPath : sourcePath);
                    switch (sourceType)
                    {
                        case AssetSourceType.LooseFile:
                            if (isolationModTag != null)
                            {
                                // Isolation rewrites the copy's internal references, so the
                                // analysis runs on the DESTINATION and only after the copy landed
                                // (never on the mod's source file).
                                await PerformLooseCopyAsync(sourcePath, destPath);
                                if (modSetting.CopyAssets)
                                {
                                    await PostProcessIsolatedCopy(destPath, isolationModTag, modSetting,
                                        outputBasePath, faceTintSubPath, ctx);
                                }
                            }
                            else if (modSetting.CopyAssets)
                            {
                                // Create two tasks: one for copying, one for analyzing the source file.
                                Task copyTask = PerformLooseCopyAsync(sourcePath, destPath);
                                Task analysisTask = PostProcessCopiedFile(sourcePath, modSetting, outputBasePath,
                                    faceTintSubPath, ctx);

                                // Await both tasks to run them in parallel.
                                await Task.WhenAll(copyTask, analysisTask);
                            }
                            else
                            {
                                await PerformLooseCopyAsync(sourcePath, destPath);
                            }

                            break;

                        case AssetSourceType.BsaFile:
                            // For BSAs, we must extract first, then analyze the extracted file.
                            // The original sequential logic is still best here.
                            var (extractOk, extractError) = await _bsaHandler.ExtractFileAsync(bsaPath, relativePath, destPath);
                            if (extractOk)
                            {
                                if (isolationModTag != null && modSetting.CopyAssets)
                                {
                                    await PostProcessIsolatedCopy(destPath, isolationModTag, modSetting,
                                        outputBasePath, faceTintSubPath, ctx);
                                }
                                else if (modSetting.CopyAssets)
                                {
                                    await PostProcessCopiedFile(destPath, modSetting, outputBasePath, faceTintSubPath, ctx);
                                }
                            }
                            else if (extractError != null &&
                                     extractError.StartsWith(BsaHandler.SharingViolationPrefix, StringComparison.Ordinal))
                            {
                                // Same deferred treatment PerformLooseCopyAsync gives file-in-use errors:
                                // LogTrueCopyFailures reports it at end of run only if the file never landed.
                                _potentialCopyFailures.TryAdd(destPath, extractError);
                            }
                            break;

                        default:
                            // If the asset is not found within this modSetting, the task simply completes,
                            // doing nothing. Another call with a different modSetting will have its own task.
                            break;
                    }
                }
                finally
                {
                    claim?.WriteLock.Release();
                }
            }
            finally
            {
                _nifProcessingSemaphore.Release();
            }
        }));
    }
    
    /// <summary>
    /// The authoritative base-game-overwrite skip decision (see RequestAssetCopyAsync): true when
    /// the destination path would overwrite a base game / Creation Club asset path, the source
    /// mod has not opted in via "Overwrite Base Game Assets", and the request is not FaceGen
    /// (by reason or by path — FaceGen files must always land at their vanilla-derived paths).
    /// <paramref name="vanillaAssetPaths"/> uses backslash separators, OrdinalIgnoreCase.
    /// Pure function, unit-testable in isolation.
    /// </summary>
    public static bool ShouldSkipAsBaseGameOverwrite(string destRelPath, string reason,
        bool overwriteBaseGameAssets, IReadOnlySet<string> vanillaAssetPaths)
    {
        if (overwriteBaseGameAssets) return false;
        if (string.Equals(reason, "FaceGen", StringComparison.OrdinalIgnoreCase)) return false;
        if (Auxilliary.IsFaceGenPath(destRelPath)) return false;
        return vanillaAssetPaths.Contains(destRelPath.Replace('/', '\\'));
    }

    /// <summary>
    /// Performs the physical copy of a loose file.
    /// </summary>
    private async Task<bool> PerformLooseCopyAsync(string sourcePath, string destPath)
    {
        try
        {
            await Task.Run(() =>
            {
                FileInfo fileInfo = Auxilliary.CreateDirectoryIfNeeded(destPath, Auxilliary.PathType.File);
                File.Copy(sourcePath, destPath, true);
            });

            // If this copy succeeded, we can safely remove any error message
            // that a concurrent, failing thread might have added for the same file.
            _potentialCopyFailures.TryRemove(destPath, out _);
            return true;
        }
        catch (IOException ioEx) when (ioEx.Message.Contains("being used by another process", StringComparison.OrdinalIgnoreCase))
        {
            // This is the specific concurrency error. Instead of logging, store the message.
            // We'll verify if the file actually failed to copy at the very end.
            string errorMessage = $"Failed to copy file from {sourcePath} to {destPath}: {ExceptionLogger.GetExceptionStack(ioEx)}";
            _potentialCopyFailures.TryAdd(destPath, errorMessage); // It's fine if another thread already added it.
            return false;
        }
        catch (Exception ex)
        {
            // Log all other types of exceptions immediately.
            AppendLog($"Failed to copy file from {sourcePath} to {destPath}: {ExceptionLogger.GetExceptionStack(ex)}", true, true);
            return false;
        }
    }

    /// <summary>
    /// After a file is copied/extracted, this checks if it is a NIF file. If so, it parses it
    /// for texture paths and recursively requests those assets.
    /// faceTintSubPath is requested explicitly so that it doesn't get erroneously copied to the wrong NPC because
    /// this function is agnostic to whether or not these textures are assigned to a surrogate, so this could potentially
    /// create the wrong face tint textures
    /// </summary>
    #region Include-As-New asset isolation

    /// <summary>Folder segment isolated copies live under, directly below the asset-type root:
    /// <c>meshes\NPC2\&lt;mod tag&gt;\...</c>, <c>textures\NPC2\&lt;mod tag&gt;\...</c>.</summary>
    public const string IsolationRootFolderName = "NPC2";

    /// <summary>Filesystem-safe per-mod segment for isolated asset destinations. Deterministic per
    /// DisplayName so every NPC in a batch lands in the same folder.</summary>
    public static string IsolationTagFor(ModSetting modSetting)
    {
        var invalid = Path.GetInvalidFileNameChars();
        var tag = new string(modSetting.DisplayName.Select(c => invalid.Contains(c) ? '_' : c).ToArray()).Trim();
        if (tag.Length > 40) tag = tag.Substring(0, 40).TrimEnd();
        return tag.Length == 0 ? "Mod" : tag;
    }

    /// <summary>"meshes\clothes\x.nif" -> "meshes\NPC2\&lt;tag&gt;\clothes\x.nif". The prefix goes UNDER
    /// the asset-type root, so a record path (relative to meshes\/textures\) stays valid after the
    /// same insertion.</summary>
    public static string InsertIsolationPrefix(string dataRelativePath, string modTag)
    {
        var sep = dataRelativePath.IndexOf(Path.DirectorySeparatorChar);
        if (sep <= 0)
        {
            return Path.Combine(IsolationRootFolderName, modTag, dataRelativePath);
        }

        return Path.Combine(dataRelativePath.Substring(0, sep), IsolationRootFolderName, modTag,
            dataRelativePath.Substring(sep + 1));
    }

    /// <summary>
    /// Asset-side counterpart of 'Include As New' (docs/SkyPatcher-IncludeAsNew-Outfit-Records.md
    /// §6). Record-level duplication keeps the source's asset paths verbatim, and for any file the
    /// donor mod itself ships that is exactly wrong for a PRIVATE copy: delivered at its original
    /// path the file either overwrites a shared/vanilla asset for the whole game (Overwrite Base
    /// Game Assets on) or is skipped by the overwrite guard and never ships at all (default) — the
    /// same all-or-nothing 'Include As New' exists to avoid, one layer down. So every asset a
    /// duplicated record references that the mod itself provides is re-pointed at an isolated
    /// destination (<c>meshes|textures\NPC2\&lt;mod&gt;\...</c>) and copied there; assets the mod does
    /// NOT ship keep their shared paths and resolve from the load order as usual. Isolated NIF
    /// copies additionally get their internal texture references isolated the same way
    /// (<see cref="PostProcessIsolatedCopy"/>). The predicate is "does the mod ship the path"
    /// (<see cref="FindAssetSource"/> never leaves the ModSetting) — deterministic and
    /// load-order-independent, unlike byte-comparison against the current winner.
    ///
    /// <para>Must run BEFORE the caller harvests the duplicates' asset links, so the harvest sees
    /// the rewritten paths. Each duplicate is visited exactly once per run — later NPCs reusing a
    /// batch duplicate skip it because its links already point at isolated (mod-absent) paths.</para>
    /// </summary>
    public void ScheduleIncludeAsNewAssetIsolation(IEnumerable<IMajorRecord> duplicatedRecords,
        ModSetting modSetting, string outputBasePath, FormKey targetNpcFormKey,
        INpcGetter appearanceNpcRecord, string npcIdentifier)
    {
        var modTag = IsolationTagFor(modSetting);
        var (_, faceTintSubPath) = Auxilliary.GetFaceGenSubPathStrings(appearanceNpcRecord.FormKey, true);

        foreach (var record in duplicatedRecords)
        {
            foreach (var link in record.EnumerateListedAssetLinks())
            {
                if (link.IsNull) continue;
                if (!Auxilliary.TryRegularizePath(link.DataRelativePath.Path, out var rel) ||
                    string.IsNullOrWhiteSpace(rel))
                {
                    continue;
                }

                if (FindAssetSource(rel, modSetting).Item1 == AssetSourceType.NotFound)
                {
                    continue; // Not the mod's file: the shared path resolves from the load order.
                }

                var isolatedRel = InsertIsolationPrefix(rel, modTag);
                var ctx = new AssetRequestContext(npcIdentifier, targetNpcFormKey,
                    appearanceNpcRecord.FormKey, appearanceNpcRecord.EditorID, "IsolatedRef",
                    $"{record.Registration.Name} '{record.EditorID}' ({record.FormKey})");
                _ = RequestAssetCopyAsync(rel, modSetting, outputBasePath, faceTintSubPath, ctx,
                    overrideDestinationRelativePath: isolatedRel, isolationModTag: modTag);

                // Weight-pair sibling (_0/_1): the engine derives it from the recorded path, so
                // once the record points into the isolation folder the sibling must live there
                // too (the original-path pipeline does the same via
                // AddCorrespondingNumericalNifPaths).
                string? siblingRel = null;
                if (rel.EndsWith("_0.nif", StringComparison.OrdinalIgnoreCase))
                    siblingRel = rel.Substring(0, rel.Length - 6) + "_1.nif";
                else if (rel.EndsWith("_1.nif", StringComparison.OrdinalIgnoreCase))
                    siblingRel = rel.Substring(0, rel.Length - 6) + "_0.nif";
                if (siblingRel != null &&
                    FindAssetSource(siblingRel, modSetting).Item1 != AssetSourceType.NotFound)
                {
                    _ = RequestAssetCopyAsync(siblingRel, modSetting, outputBasePath, faceTintSubPath,
                        ctx.WithReferencer(ctx.Referencer + " (weight pair)"),
                        overrideDestinationRelativePath: InsertIsolationPrefix(siblingRel, modTag),
                        isolationModTag: modTag);
                }

                if (!link.TrySetPath(isolatedRel))
                {
                    AppendLog($"      WARNING: could not re-point {record.EditorID ?? record.FormKey.ToString()} " +
                              $"asset '{rel}' at its isolated copy '{isolatedRel}'; the shared path remains.",
                        true, true);
                }
            }
        }
    }

    /// <summary>
    /// Post-copy processing for an isolated destination file (replaces
    /// <see cref="PostProcessCopiedFile"/> for isolation copies, and runs on the DESTINATION after
    /// the copy lands — the rewrite must never touch the mod's source file). For NIFs: every
    /// internal texture the mod itself ships is scheduled for an isolated copy and the slot path
    /// rewritten to match; textures the mod does not ship keep their shared paths. SMP physics
    /// XMLs are scheduled through the standard machinery at their ORIGINAL paths — XML paths are
    /// mod-specific by convention (vanilla ships none), so the original and isolated mesh can
    /// safely share them.
    /// </summary>
    private async Task PostProcessIsolatedCopy(string copiedDestPath, string isolationModTag,
        ModSetting modSetting, string outputBasePath, string faceTintSubPath, AssetRequestContext ctx)
    {
        if (!copiedDestPath.EndsWith(".nif", StringComparison.OrdinalIgnoreCase)) return;

        ScheduleSmpPhysicsXmls(copiedDestPath, modSetting, outputBasePath, faceTintSubPath, ctx);

        try
        {
            var texCtx = ctx.WithReason("IsolatedNifTexture", Path.GetFileName(copiedDestPath));
            // Slot-level harvest (not the block walk) so the remap keys match exactly what the
            // slot-level rewriter will read back.
            var remap = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (var (_, texturePaths) in NifHandler.GetTexturesByShape(copiedDestPath))
            {
                foreach (var tex in texturePaths)
                {
                    if (remap.ContainsKey(tex)) continue;
                    if (!string.IsNullOrEmpty(faceTintSubPath) &&
                        (faceTintSubPath.Contains(tex, StringComparison.OrdinalIgnoreCase) ||
                         tex.Contains(faceTintSubPath, StringComparison.OrdinalIgnoreCase)))
                    {
                        continue;
                    }
                    if (!Auxilliary.TryRegularizePath(tex, out var rel) || string.IsNullOrWhiteSpace(rel))
                    {
                        continue;
                    }
                    if (FindAssetSource(rel, modSetting).Item1 == AssetSourceType.NotFound)
                    {
                        continue; // Shared texture: leave the path; the load order supplies it.
                    }

                    var isolatedRel = InsertIsolationPrefix(rel, isolationModTag);
                    remap[tex] = isolatedRel;
                    _ = RequestAssetCopyAsync(rel, modSetting, outputBasePath, faceTintSubPath, texCtx,
                        overrideDestinationRelativePath: isolatedRel);
                }
            }

            if (remap.Count > 0)
            {
                int rewritten = NifHandler.RewriteTexturePaths(copiedDestPath, remap,
                    msg => AppendLog("      " + msg, true, true));
                Debug.WriteLine($"      Isolation: rewrote {rewritten} texture slot(s) in {Path.GetFileName(copiedDestPath)}.");
            }

            await WarnOnFullyUnresolvedShapeTextures(copiedDestPath, modSetting, faceTintSubPath, ctx);
        }
        catch (Exception ex)
        {
            AppendLog($"ISOLATED NIF ERROR: Failed to isolate texture references of '{copiedDestPath}': " +
                      ExceptionLogger.GetExceptionStack(ex), true, true);
        }
    }

    #endregion

    private async Task PostProcessNifTextures(string nifPathToAnalyze, ModSetting modSetting, string outputBasePath, string faceTintSubPath, AssetRequestContext ctx)
    {
        // The check now correctly uses the passed-in path.
        if (!nifPathToAnalyze.EndsWith(".nif", StringComparison.OrdinalIgnoreCase)) return;

        // Also follow any SMP/HDT physics XML this NIF points at (independent of textures).
        ScheduleSmpPhysicsXmls(nifPathToAnalyze, modSetting, outputBasePath, faceTintSubPath, ctx);

        try
        {
            // The analysis now happens on the source NIF file.
            var texturesInNif = NifHandler.GetExtraTexturesFromNif(nifPathToAnalyze);
            var regularizedPaths = new HashSet<string>();
            foreach (var t in texturesInNif)
            {
                if (faceTintSubPath.Contains(t, StringComparison.OrdinalIgnoreCase) || t.Contains(faceTintSubPath, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }
                Auxilliary.TryRegularizePath(t, out var regularizedPath);
                regularizedPaths.Add(regularizedPath);
            }

            if (!regularizedPaths.Any()) return;

            // This debug message remains useful.
            Debug.WriteLine($"      NIF Analysis: Found {regularizedPaths.Count} additional textures in {Path.GetFileName(nifPathToAnalyze)}.");

            var textureTasks = new List<Task>();
            var texCtx = ctx.WithReason("NifTexture", Path.GetFileName(nifPathToAnalyze));
            foreach (var texRelPath in regularizedPaths)
            {
                textureTasks.Add(RequestAssetCopyAsync(texRelPath, modSetting, outputBasePath, faceTintSubPath, texCtx));
            }
            // await Task.WhenAll(textureTasks); DO not await here - causes deadlock due to upstream semaphore

            await WarnOnFullyUnresolvedShapeTextures(nifPathToAnalyze, modSetting, faceTintSubPath, ctx);
        }
        catch (Exception ex)
        {
            AppendLog($"NIF TEXTURE ERROR: Failed to parse '{nifPathToAnalyze}' for additional textures: {ExceptionLogger.GetExceptionStack(ex)}", true, true);
        }
    }

    /// <summary>
    /// Records a copied NIF's shapes whose textures are ALL unresolvable, for the end-of-run
    /// per-NPC warning report (<see cref="NpcWarningReporter"/>, kind
    /// <see cref="NpcWarningKind.TexturelessShapes"/>).
    ///
    /// <para>Deliberately per SHAPE rather than per texture. Mods routinely ship a NIF with one
    /// dead slot — an absent mouth subsurface map is near-universal — and warning on every one
    /// buries the signal in noise the user cannot act on. A shape with no resolvable texture at
    /// all is different in kind: it renders untextured in game, which is the visible symptom that
    /// sent the Adrianne Avenicci investigation (Bijin AIO De-Standalone's hair/brow/eye shapes
    /// reference textures owned by a sibling mod, and <see cref="FindAssetSource"/> never leaves
    /// the selected ModSetting).</para>
    ///
    /// <para>"Unresolvable" is judged against everything the game can actually load, not just the
    /// selected mod: the mod's own folders and BSAs (<see cref="FindAssetSource"/>), then a loose
    /// file in the game Data folder, then the vanilla archives. Without those last two, every mod
    /// NIF that legitimately reuses a vanilla texture would be reported.</para>
    ///
    /// <para>Deduplicated by (mod, NIF, shape) so a shared mesh used by hundreds of NPCs is
    /// recorded once, against the first NPC that hit it, not hundreds of times.</para>
    /// </summary>
    private async Task WarnOnFullyUnresolvedShapeTextures(
        string nifPathToAnalyze, ModSetting modSetting, string faceTintSubPath, AssetRequestContext ctx)
    {
        // A mesh only a HeadPart record named is not what the engine draws — the face comes from the
        // shapes baked into the FaceGen NIF, which is scanned on its own and reports for real. Mod
        // authors commonly retarget the baked geometry's textures without updating the HDPT record,
        // leaving it pointing at a donor mesh whose textures were never installed; warning on that
        // claims an NPC will render untextured while their face renders correctly. See
        // AssetRequestContext.HeadPartOnly. ArmorAddon meshes ARE drawn, so they stay reportable.
        if (ctx.HeadPartOnly) return;

        IReadOnlyList<(string ShapeName, IReadOnlyList<string> TexturePaths)> byShape;
        try
        {
            byShape = NifHandler.GetTexturesByShape(nifPathToAnalyze);
        }
        catch
        {
            return; // A diagnostic must never fail a patch run; the copy already succeeded.
        }
        if (byShape.Count == 0) return;

        IReadOnlySet<string>? vanillaAssetPaths = null;
        string dataFolder = _environmentStateProvider.DataFolderPath;

        foreach (var (shapeName, texturePaths) in byShape)
        {
            var candidates = new List<string>();
            foreach (var tex in texturePaths)
            {
                // The face tint is supplied by the FaceGen ladder, not by this scan; a head shape
                // whose only texture is its tint is not textureless.
                if (!string.IsNullOrEmpty(faceTintSubPath) &&
                    (faceTintSubPath.Contains(tex, StringComparison.OrdinalIgnoreCase) ||
                     tex.Contains(faceTintSubPath, StringComparison.OrdinalIgnoreCase)))
                {
                    continue;
                }
                if (Auxilliary.TryRegularizePath(tex, out var rel) && !string.IsNullOrWhiteSpace(rel))
                {
                    candidates.Add(rel);
                }
            }

            if (candidates.Count == 0) continue; // No textures to be missing.

            vanillaAssetPaths ??= await _bsaHandler.GetVanillaAssetPathsAsync();

            bool anyResolved = false;
            foreach (var rel in candidates)
            {
                if (FindAssetSource(rel, modSetting).Item1 != AssetSourceType.NotFound ||
                    vanillaAssetPaths.Contains(rel) ||
                    (!string.IsNullOrWhiteSpace(dataFolder) && File.Exists(Path.Combine(dataFolder, rel))))
                {
                    anyResolved = true;
                    break;
                }
            }
            if (anyResolved) continue;

            string dedupeKey = $"{modSetting.DisplayName}|{nifPathToAnalyze}|{shapeName}";
            if (!_reportedTextureless.TryAdd(dedupeKey, 0)) continue;

            string who = string.IsNullOrWhiteSpace(ctx.NpcIdentifier) ? "an NPC" : ctx.NpcIdentifier;
            string shape = string.IsNullOrWhiteSpace(shapeName) ? "(unnamed shape)" : shapeName;
            NpcWarningReporter.Record(NpcWarningKind.TexturelessShapes, who,
                $"{Path.GetFileName(nifPathToAnalyze)} '{shape}' (missing: {string.Join(", ", candidates)})",
                technicalDetail: $"mod='{modSetting.DisplayName}' nif={nifPathToAnalyze}\n" +
                                 $"shape '{shape}' unresolved slots: {string.Join(", ", candidates)}");
        }
    }

    /// <summary>
    /// After a file is copied/extracted, runs the appropriate per-type post-processing:
    /// NIFs are scanned for referenced textures and physics XMLs; physics XMLs are scanned for
    /// any sibling XML they include. Non-NIF/non-XML files need no follow-up.
    /// </summary>
    private async Task PostProcessCopiedFile(string pathToAnalyze, ModSetting modSetting, string outputBasePath, string faceTintSubPath, AssetRequestContext ctx)
    {
        if (pathToAnalyze.EndsWith(".nif", StringComparison.OrdinalIgnoreCase))
        {
            await PostProcessNifTextures(pathToAnalyze, modSetting, outputBasePath, faceTintSubPath, ctx);
        }
        else if (pathToAnalyze.EndsWith(".xml", StringComparison.OrdinalIgnoreCase))
        {
            PostProcessSmpXmlIncludes(pathToAnalyze, modSetting, outputBasePath, faceTintSubPath, ctx);
        }
    }

    /// <summary>
    /// SMP/HDT physics is linked to a mesh by an NiStringExtraData block inside the NIF whose value is
    /// the (Data-relative) path to a physics XML config (see <see cref="NifHandler.GetPhysicsXmlPathsFromNif"/>).
    /// The game (hdtSMP64) reads that path to load hair/wig/armor/body physics; NPC2 previously never copied
    /// these XMLs, so forwarded appearances lost their physics. For every NIF we copy for an NPC, we follow its
    /// embedded reference and schedule the XML for copy too - which scopes the copy to exactly the meshes the
    /// NPC uses, so we never guess or over-copy. Fire-and-forget like the texture scan (must NOT await while the
    /// caller holds <see cref="_nifProcessingSemaphore"/>).
    /// </summary>
    private void ScheduleSmpPhysicsXmls(string nifPathToAnalyze, ModSetting modSetting, string outputBasePath, string faceTintSubPath, AssetRequestContext ctx)
    {
        try
        {
            var xmlRefs = NifHandler.GetPhysicsXmlPathsFromNif(nifPathToAnalyze);
            var xmlCtx = ctx.WithReason("SmpXml", Path.GetFileName(nifPathToAnalyze));
            foreach (var raw in xmlRefs)
            {
                if (!TryNormalizePhysicsXmlPath(raw, nifPathToAnalyze, out var xmlRelPath)) continue;

                // Only this mod's own files - a missing XML usually means the mesh relies on the global
                // SKSE/Plugins/hdtSkinnedMeshConfigs/defaultBBPs.xml name-map, which is not part of the mod folder.
                if (FindAssetSource(xmlRelPath, modSetting).Item1 == AssetSourceType.NotFound)
                {
                    AppendLog($"  SMP physics XML '{xmlRelPath}' referenced by {Path.GetFileName(nifPathToAnalyze)} " +
                              $"was not found in '{modSetting.DisplayName}' (may rely on a global defaultBBPs.xml mapping).", false, false);
                    continue;
                }

                Debug.WriteLine($"      SMP Physics: scheduling '{xmlRelPath}' (from {Path.GetFileName(nifPathToAnalyze)}).");
                _ = RequestAssetCopyAsync(xmlRelPath, modSetting, outputBasePath, faceTintSubPath, xmlCtx);
            }
        }
        catch (Exception ex)
        {
            AppendLog($"SMP PHYSICS ERROR: Failed to scan '{nifPathToAnalyze}' for physics XML: {ExceptionLogger.GetExceptionStack(ex)}", true, true);
        }
    }

    /// <summary>
    /// A physics XML may reference sibling XML files. This follows any file-path-like ".xml" reference in a
    /// copied physics XML so include chains are carried along too. References that don't resolve to one of the
    /// mod's files are silently ignored (they are speculative). Fire-and-forget, like the NIF scans.
    /// </summary>
    private void PostProcessSmpXmlIncludes(string xmlPathToAnalyze, ModSetting modSetting, string outputBasePath, string faceTintSubPath, AssetRequestContext ctx)
    {
        try
        {
            if (!File.Exists(xmlPathToAnalyze)) return;
            string content = File.ReadAllText(xmlPathToAnalyze);

            // Match quoted/element values that look like real relative paths (contain a separator) ending in .xml.
            var matches = System.Text.RegularExpressions.Regex.Matches(
                content,
                "[\"'>]\\s*([^\"'<>|*?\\r\\n]+[\\\\/][^\"'<>|*?\\r\\n]+\\.xml)\\s*[\"'<]",
                System.Text.RegularExpressions.RegexOptions.IgnoreCase);

            var includeCtx = ctx.WithReason("SmpXml", Path.GetFileName(xmlPathToAnalyze));
            foreach (System.Text.RegularExpressions.Match m in matches)
            {
                var token = m.Groups[1].Value;
                if (token.Contains("://")) continue; // skip URLs / schema references
                if (!TryNormalizePhysicsXmlPath(token, xmlPathToAnalyze, out var relPath)) continue;
                if (FindAssetSource(relPath, modSetting).Item1 == AssetSourceType.NotFound) continue;

                Debug.WriteLine($"      SMP Physics: scheduling included '{relPath}' (from {Path.GetFileName(xmlPathToAnalyze)}).");
                _ = RequestAssetCopyAsync(relPath, modSetting, outputBasePath, faceTintSubPath, includeCtx);
            }
        }
        catch (Exception ex)
        {
            AppendLog($"SMP XML INCLUDE ERROR: Failed to scan '{xmlPathToAnalyze}': {ExceptionLogger.GetExceptionStack(ex)}", true, true);
        }
    }

    /// <summary>
    /// Normalizes a physics-XML reference (as stored in an NiStringExtraData or an XML include) into a
    /// Data-relative path suitable for <see cref="FindAssetSource"/>. Handles forward slashes, a leading
    /// "...\data\" prefix, and a bare filename (resolved relative to the analyzed NIF/XML's own folder).
    /// Internal (not private) so <see cref="HeadPartWigConverter"/> resolves a wig NIF's physics
    /// reference through the exact same rules.
    /// </summary>
    internal static bool TryNormalizePhysicsXmlPath(string rawValue, string analyzedFilePath, out string xmlRelPath)
    {
        xmlRelPath = string.Empty;
        if (string.IsNullOrWhiteSpace(rawValue)) return false;

        var cleaned = rawValue.Replace('/', '\\').Trim().Trim('"').TrimStart('\\');
        var segs = cleaned.Split('\\', StringSplitOptions.RemoveEmptyEntries).ToList();

        // Strip a leading "...\data\" prefix if the path was stored with one.
        int dataIdx = segs.FindIndex(s => s.Equals("data", StringComparison.OrdinalIgnoreCase));
        if (dataIdx >= 0 && dataIdx + 1 < segs.Count)
            segs = segs.Skip(dataIdx + 1).ToList();

        if (segs.Count == 0) return false;

        if (segs.Count == 1)
        {
            // Bare filename: resolve relative to the analyzed file's Data-relative directory (anchored on "meshes").
            var anchorSegs = analyzedFilePath.Replace('/', '\\').Split('\\', StringSplitOptions.RemoveEmptyEntries);
            int meshesIdx = Array.FindIndex(anchorSegs, s => s.Equals("meshes", StringComparison.OrdinalIgnoreCase));
            if (meshesIdx < 0 || meshesIdx >= anchorSegs.Length - 1) return false;
            var dirSegs = anchorSegs.Skip(meshesIdx).Take(anchorSegs.Length - meshesIdx - 1);
            xmlRelPath = string.Join("\\", dirSegs) + "\\" + segs[0];
            return true;
        }

        xmlRelPath = string.Join("\\", segs);
        return true;
    }

    /// <summary>
    /// Finds the source of a given asset, checking loose files first, then BSAs.
    /// </summary>
    private (AssetSourceType, string SourcePath, string BsaPath) FindAssetSource(string relativePath, ModSetting modSetting)
    {
        // 1. Check loose files in the mod's folders
        // Iterate in reverse order so the last path "wins" if the same relative path is present in multiple mod folders
        for (int i = modSetting.CorrespondingFolderPaths.Count - 1; i >= 0; i--)
        {
            var dirPath = modSetting.CorrespondingFolderPaths[i];
            var candidatePath = Path.Combine(dirPath, relativePath);
            if (FileExists(candidatePath, modSetting.DisplayName, dirPath))
            {
                return (AssetSourceType.LooseFile, candidatePath, string.Empty);
            }
        }
        
        // 2. Check BSAs associated with the mod. Folder-scoped first: the BSA
        // index is keyed by plugin FILENAME (ModKey), and two NPC2 mods can
        // ship the same plugin name in different folders with different BSA
        // content — the folder-blind broadcast would serve whichever variant's
        // archive matched first, extracting another mod's bytes into this
        // mod's output. Iterate folders in reverse to match the loose-file
        // last-path-wins convention above.
        foreach (var modKey in modSetting.CorrespondingModKeys)
        {
            for (int i = modSetting.CorrespondingFolderPaths.Count - 1; i >= 0; i--)
            {
                if (_bsaHandler.FileExistsInArchiveAtFolder(relativePath, modKey,
                        modSetting.CorrespondingFolderPaths[i], out var scopedBsaPath) &&
                    scopedBsaPath != null)
                {
                    return (AssetSourceType.BsaFile, relativePath, scopedBsaPath);
                }
            }
        }

        // Folder-blind fallback: synthetic entries ("Base Game"/"Creation
        // Club") carry no CorrespondingFolderPaths — their archives live in
        // the game Data folder — and some mods reference assets from BSAs
        // outside their own folders. A scoped miss falling through to the
        // broadcast preserves the previous behavior for those cases.
        foreach (var modKey in modSetting.CorrespondingModKeys)
        {
            if (_bsaHandler.FileExists(relativePath, modKey, out var bsaPath) && bsaPath != null)
            {
                return (AssetSourceType.BsaFile, relativePath, bsaPath);
            }
        }

        return (AssetSourceType.NotFound, string.Empty, string.Empty);
    }
    
