    private readonly ConcurrentDictionary<string, Task> _processedAssetTasks = new(StringComparer.OrdinalIgnoreCase);

    // Guards against two mods writing the same output file. The task cache above is deliberately
    // per-(file|mod) so one mod's failed lookup can't block another's, but that means two mods
    // that ship the same asset path (e.g. sibling mods sharing an author's resource BSA) get two
    // concurrent tasks targeting one destination, racing File.Create against each other. The
    // first task to resolve a real source claims the destination and the rest skip their write —
    // except that a real mod always dethrones the synthetic Base Game / Creation Club entries
    // (their copy is just the vanilla bytes the game already has), with the actual writes
    // serialized through the claim's WriteLock so a takeover can't re-create the race.
    private sealed class DestinationClaim
    {
        public string OwnerCacheKey = string.Empty;
        public bool OwnerIsAutoGenerated;
        public readonly SemaphoreSlim WriteLock = new(1, 1);
    }

    private readonly ConcurrentDictionary<string, DestinationClaim> _claimedDestinations = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>(mod|nif|shape) keys already recorded by
