    /// <summary>How (or whether) a mod supplies an asset, as the ladder's public presence enum.</summary>
    public FaceGenAssetPresence GetAssetPresence(string relativePath, ModSetting modSetting)
    {
        var (sourceType, _, _) = FindAssetSource(relativePath, modSetting);
        return sourceType switch
        {
            AssetSourceType.LooseFile => FaceGenAssetPresence.LooseFile,
            AssetSourceType.BsaFile => FaceGenAssetPresence.BsaFile,
            _ => FaceGenAssetPresence.NotFound,
        };
    }

    /// <summary>
    /// The mod entry that owns the plugin an NPC is first defined in — the "mod of origin".
    /// Resolution is by <see cref="ModSetting.CorrespondingModKeys"/>, preferring an entry that
    /// actually has the asset in hand, because a plugin name can legitimately appear in more than
    /// one entry (a mod bundling a patched copy of another's plugin). The synthetic Base Game /
    /// Creation Club entries are the natural answer for vanilla and CC keys, and are preferred
    /// when nothing else has the file, since their assets live in the game's own BSAs.
    /// </summary>
    public ModSetting? FindOriginModSetting(ModKey originKey, string? assetRelPathHint = null)
    {
        var candidates = _settings.ModSettings
            .Where(ms => ms.CorrespondingModKeys.Contains(originKey))
            .ToList();

        if (candidates.Count == 0) return null;
        if (candidates.Count == 1) return candidates[0];

        if (!string.IsNullOrEmpty(assetRelPathHint))
        {
            var holder = candidates.FirstOrDefault(ms => AssetExists(assetRelPathHint, ms));
            if (holder != null) return holder;
        }

        return candidates.FirstOrDefault(ms => ms.IsAutoGenerated) ?? candidates[0];
    }

    /// <summary>
    /// Whether anything in the live load order currently supplies <paramref name="relativePath"/> —
    /// the "conflict winner". Under a mod manager the Data folder IS the merged virtual view, so a
    /// single existence check answers it correctly; BSAs are consulted as the fallback the game
    /// itself would use.
    ///
    /// <para>A file this app wrote on a previous run does not count: if the output mod still holds
    /// an identical copy, the apparent winner is our own stale output and treating it as an
    /// independent source would let a bad result validate itself.</para>
    /// </summary>
    public bool WinningAssetExists(string relativePath, out string? ownerModName)
    {
        ownerModName = null;
        string rel = relativePath.Replace('/', '\\').TrimStart('\\');

        try
        {
            string dataPath = Path.Combine(_environmentStateProvider.DataFolderPath, rel);
            if (File.Exists(dataPath))
            {
                if (IsOurOwnPriorOutput(rel, dataPath)) return false;
                ownerModName = DescribeLooseProvider(rel);
                return true;
            }
        }
        catch
        {
            // An unreadable Data path just falls through to the archive check.
        }

        foreach (var modKey in _environmentStateProvider.LoadOrderModKeys)
        {
            if (_bsaHandler.FileExists(rel, modKey, out var bsaPath) && bsaPath != null)
            {
                ownerModName = Path.GetFileName(bsaPath);
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Produces a real file path for an asset so a parser can open it, extracting to
    /// <paramref name="tempDir"/> when the source is inside a BSA. Returns null when the mod does
    /// not supply the asset at all. The caller owns cleanup of anything under tempDir.
    ///
    /// <para>Needed by the ladder's head-part compatibility check, which parses a candidate FaceGen
    /// NIF — and the candidates (vanilla, or a mod's own archive) are usually BSA-resident.</para>
    /// </summary>
    public async Task<string?> MaterializeAssetAsync(string relativePath, ModSetting modSetting, string tempDir)
    {
        var (sourceType, sourcePath, bsaPath) = FindAssetSource(relativePath, modSetting);

        switch (sourceType)
        {
            case AssetSourceType.LooseFile:
                return sourcePath;

            case AssetSourceType.BsaFile:
                try
                {
                    Directory.CreateDirectory(tempDir);
                    string dest = Path.Combine(tempDir,
                        Guid.NewGuid().ToString("N") + Path.GetExtension(relativePath));
                    var (ok, _) = await _bsaHandler.ExtractFileAsync(bsaPath, relativePath, dest);
                    return ok ? dest : null;
                }
                catch
                {
                    return null;
                }

            default:
                return null;
        }
    }

    /// <summary>
    /// Winner-side twin of <see cref="MaterializeAssetAsync"/>: produces a real file path for the
    /// LOAD-ORDER-WINNING copy of an asset so a parser can open it, extracting to
    /// <paramref name="tempDir"/> when the winner is BSA-resident. Same search and exclusions as
    /// <see cref="WinningAssetExists"/>, so the two always agree on what "the winner" is: a loose
    /// Data-folder file first (a loose file that is this app's own prior output means no
    /// third-party winner — null, no archive fallback), then the load order's archives. Null when
    /// nothing wins. The caller owns cleanup of anything under tempDir.
    ///
    /// <para>Exists because the ladder's winner-side compatibility probe used the loose-only
    /// <see cref="GetWinningAssetPath"/> and silently returned NotEvaluated for BSA-packed
    /// winners — accepted unprobed via <c>?? true</c> — while the origin side always extracted
    /// (seam fixed 2026-07-30).</para>
    /// </summary>
    public async Task<string?> MaterializeWinningAssetAsync(string relativePath, string tempDir)
    {
        string rel = relativePath.Replace('/', '\\').TrimStart('\\');

        try
        {
            string dataPath = Path.Combine(_environmentStateProvider.DataFolderPath, rel);
            if (File.Exists(dataPath))
            {
                return IsOurOwnPriorOutput(rel, dataPath) ? null : dataPath;
            }
        }
        catch
        {
            // An unreadable Data path just falls through to the archive check.
        }

        foreach (var modKey in _environmentStateProvider.LoadOrderModKeys)
        {
            if (_bsaHandler.FileExists(rel, modKey, out var bsaPath) && bsaPath != null)
            {
                try
                {
                    Directory.CreateDirectory(tempDir);
                    string dest = Path.Combine(tempDir,
                        Guid.NewGuid().ToString("N") + Path.GetExtension(rel));
                    var (ok, _) = await _bsaHandler.ExtractFileAsync(bsaPath, rel, dest);
                    return ok ? dest : null;
                }
                catch
                {
                    return null;
                }
            }
        }

        return null;
    }

    /// <summary>The live Data-folder path for an asset, or null if nothing is deployed there.
    /// This is the "winner" the game itself would load.</summary>
    public string? GetWinningAssetPath(string relativePath)
    {
        try
        {
            string path = Path.Combine(_environmentStateProvider.DataFolderPath,
                relativePath.Replace('/', '\\').TrimStart('\\'));
            return File.Exists(path) ? path : null;
        }
        catch
        {
            return null;
        }
    }

    /// <summary>True when the output mod folder holds a byte-identical copy of the file that is
    /// currently winning, i.e. the winner is this app's own previous output.</summary>
    private bool IsOurOwnPriorOutput(string relativePath, string winningPath)
    {
        var outputFolder = _environmentStateProvider.OutputModFolderPath;
        if (string.IsNullOrWhiteSpace(outputFolder)) return false;

        try
        {
            string ourCopy = Path.Combine(outputFolder, relativePath);
            if (!File.Exists(ourCopy)) return false;

            var a = new FileInfo(ourCopy);
            var b = new FileInfo(winningPath);
            if (a.Length != b.Length) return false;

            return File.ReadAllBytes(ourCopy).AsSpan().SequenceEqual(File.ReadAllBytes(winningPath));
        }
        catch
        {
            return false;
        }
    }

    /// <summary>Best-effort name of the mod folder supplying a loose asset, for log messages.
    /// Only the folder name is needed, so this stops at the first match.</summary>
    private string? DescribeLooseProvider(string relativePath)
    {
        var modsFolder = _settings.ModsFolder;
        if (string.IsNullOrWhiteSpace(modsFolder) || !Directory.Exists(modsFolder)) return null;

        try
        {
            foreach (var dir in Directory.EnumerateDirectories(modsFolder))
            {
                if (File.Exists(Path.Combine(dir, relativePath)))
                {
                    return Path.GetFileName(dir);
                }
            }
        }
        catch
        {
            // Naming the provider is a nicety; failing to is not an error.
        }

        return null;
    }
    
