    /// <summary>
    /// Orchestrates copying assets for a specific NPC by identifying all required assets
    /// and scheduling them for asynchronous processing.
    /// </summary>
    /// <param name="faceGenDecision">
    /// The ladder's verdict for this NPC (see <see cref="FaceGenLadder"/>), computed by the Patcher
    /// before any record was written so an unpatchable face could abort early. It decides where
    /// each half of the FaceGen comes from; everything else here is unaffected by it.
    /// </param>
    public async Task ScheduleCopyNpcAssets(
        FormKey targetNpcFormKey, // the NPC to which the appearance is being applied
        INpcGetter appearanceNpcRecord,
        ModSetting appearanceModSetting,
        string outputBasePath,
        string npcIdentifier,
        FaceGenLadderDecision faceGenDecision)
    {
        using var _ = ContextualPerformanceTracer.Trace("AssertHandler.ScheduleCopyNpcAssets");
        RunLog(
            $"    Copying assets for {appearanceNpcRecord.EditorID ?? appearanceNpcRecord.FormKey.ToString()} from sources related to '{appearanceModSetting.DisplayName}'..."); // Verbose only

        // Assets can be sourced from loose files (CorrespondingFolderPaths) OR from BSAs
        // (resolved via CorrespondingModKeys) — FindAssetSource checks both. Synthetic
        // entries like "Base Game"/"Creation Club" carry no folder paths because their
        // assets (incl. vanilla FaceGen) live in the game BSAs, so a folder-paths-only
        // guard would wrongly skip all copying for them — e.g. a shared appearance whose
        // donor's FaceGen comes from a vanilla BSA. Only bail when neither source exists.
        bool hasFolderSources = (appearanceModSetting.CorrespondingFolderPaths?.Any() ?? false);
        bool hasBsaSources = appearanceModSetting.CorrespondingModKeys.Any();
        if (!hasFolderSources && !hasBsaSources)
        {
            RunLog(
                $"      WARNING: Mod Setting '{appearanceModSetting.DisplayName}' has no Corresponding Folder Paths or plugins. Cannot copy assets."); // Verbose only (Warning)
            return;
        }

        // --- Identify Required Assets ---
        HashSet<string> meshToCopyRelativePaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        HashSet<string> textureToCopyRelativePaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var baseModKey = appearanceNpcRecord.FormKey.ModKey;

        // 1. FaceGen Assets — sourced per the ladder's verdict (see FaceGenLadder). The SOURCE is
        // always the subject's path (the end of the donor's Traits chain), because a templated
        // donor has no face of its own; the DESTINATION depends on what the output record will
        // look like to the engine, resolved just below.
        var (subjectMeshRelPath, subjectTexRelPath) =
            Auxilliary.GetFaceGenSubPathStrings(faceGenDecision.Inputs.SubjectFormKey, true);

        // faceTintSubPath is threaded into NIF post-processing, which expects the tint that pairs
        // with the mesh being copied — i.e. the subject's.
        string faceTexRelativePath = subjectTexRelPath;

        FormKey surrogateNpcFormKey = FormKey.Null;
        bool useSkyPatcher =
            _skyPatcherInterface.TryGetSurrogateFormKey(targetNpcFormKey, out surrogateNpcFormKey);
        bool isFaceSwap = !targetNpcFormKey.Equals(appearanceNpcRecord.FormKey);

        // Which FormKey's FaceGen paths this pass may write to — always the record it is itself
        // writing: the surrogate in SkyPatcher mode, the target on a face swap, otherwise the NPC's
        // own. Never another NPC's, even when the engine would read that one instead. A mesh is
        // reconciled against the head parts of whatever record sits at its path, so writing under a
        // record this pass does not patch pairs a mod's mesh with someone else's unpatched record —
        // the dark-face bug, on an NPC nobody selected.
        //
        // An output record that still inherits therefore has no destination at all. The ladder
        // reaches the same conclusion from the same inputs and chooses no source
        // (FaceGenLadder.KeepsInheritedFace), so both halves below are no-ops for those NPCs and
        // the run reports them at the end.
        FormKey destinationFormKey =
            useSkyPatcher ? surrogateNpcFormKey
            : isFaceSwap ? targetNpcFormKey
            : appearanceNpcRecord.FormKey;

        var (destMeshRelPath, destTexRelPath) =
            Auxilliary.GetFaceGenSubPathStrings(destinationFormKey, true);

        // Provenance context for the opt-in AssetProvenance report (no-op unless enabled): every
        // asset scheduled below is attributed to this target NPC + donor + mod, with a per-asset
        // reason. faceGenRelPaths lets the final loop tell the NPC's own FaceGen apart from assets
        // pulled in by the appearance plugin's records.
        var faceGenCtx = new AssetRequestContext(npcIdentifier, targetNpcFormKey, appearanceNpcRecord.FormKey, appearanceNpcRecord.EditorID, "FaceGen");
        var pluginRefCtx = faceGenCtx.WithReason("PluginRef");
        var faceGenRelPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { subjectMeshRelPath, subjectTexRelPath };

        if (!string.IsNullOrWhiteSpace(faceGenDecision.LogLine))
        {
            // Named, and verbose-only. The ladder's sentences say "this NPC", and the line that
            // says WHICH one ("- Processing: ...") is itself verbose — so force-logging these left
            // an unattributable sentence stranded between two batch headers with no NPC anywhere
            // near it. Aborts are unaffected: they never reach here (the patcher returns before
            // scheduling any assets) and stay forced, both individually and in the end-of-run
            // skipped-NPC summary.
            RunLog($"      {npcIdentifier}: {faceGenDecision.LogLine}");
        }

        // The FaceGen outcomes short of an abort that the user has to do something about.
        // Recorded here and reported AFTER patching by NpcWarningReporter, grouped by warning
        // type with one explanation per group — warning lines emitted as processing happened
        // were scattered through the run log and easy to miss (user direction, 2026-07-30).
        if (faceGenDecision.MissingTintEverywhere)
        {
            NpcWarningReporter.Record(NpcWarningKind.MissingFaceTint, npcIdentifier,
                technicalDetail: faceGenDecision.TechnicalSummary);
        }
        if (faceGenDecision.OriginMeshFailedCompatCheck)
        {
            NpcWarningReporter.Record(NpcWarningKind.OriginMeshCompatibility, npcIdentifier,
                technicalDetail: faceGenDecision.TechnicalSummary);
        }
        if (faceGenDecision.ModMeshFailedCompatCheck)
        {
            NpcWarningReporter.Record(NpcWarningKind.ModMeshCompatibility, npcIdentifier,
                technicalDetail: faceGenDecision.TechnicalSummary);
        }

        // Both are no-ops when the ladder chose no source, which is how an inheriting NPC copies
        // nothing. The deferral that used to sit here — "skip if the terminus has its own
        // selection, because its pass owns that shared path" — is gone: nothing writes to another
        // NPC's path any more, so there is no contention left to arbitrate.
        ScheduleFaceGenHalf(faceGenDecision.NifChoice, subjectMeshRelPath, destMeshRelPath,
            appearanceModSetting, outputBasePath, faceTexRelativePath, faceGenCtx, npcIdentifier);
        ScheduleFaceGenHalf(faceGenDecision.DdsChoice, subjectTexRelPath, destTexRelPath,
            appearanceModSetting, outputBasePath, faceTexRelativePath, faceGenCtx, npcIdentifier);

        // 2. Non-FaceGen Assets (Only if CopyExtraAssets is true)
        // When the AssetProvenance diag is on, assetProv accumulates path -> referencing-record so the
        // report names exactly which record pulled each PluginRef asset in. Null (skipped) when off.
        Dictionary<string, HashSet<string>>? assetProv =
            AssetProvenanceDiag.IsEnabled ? new Dictionary<string, HashSet<string>>(StringComparer.OrdinalIgnoreCase) : null;
        // Meshes only a HeadPart record named. Tracked unconditionally (unlike assetProv): the
        // textureless-shape warning skips them because the engine draws the face from the FaceGen
        // NIF's baked shapes, not from these — see AssetRequestContext.HeadPartOnly.
        var headPartOnlyMeshPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        if (appearanceModSetting.CopyAssets)
        {
            GetAssetPathsReferencedByPlugin(appearanceNpcRecord, appearanceModSetting.CorrespondingModKeys, appearanceModSetting.CorrespondingFolderPaths.ToHashSet(), meshToCopyRelativePaths, textureToCopyRelativePaths, assetProv, headPartOnlyMeshPaths);
            AddCorrespondingNumericalNifPaths(meshToCopyRelativePaths, new HashSet<string>());
        }

        // 3. Schedule all identified assets for processing
        var allAssetPaths = meshToCopyRelativePaths.Concat(textureToCopyRelativePaths).ToHashSet(StringComparer.OrdinalIgnoreCase);

        AppendLog($"      Identified {allAssetPaths.Count} unique assets to process for {appearanceNpcRecord.EditorID ?? appearanceNpcRecord.FormKey.ToString()}.");

        foreach (var relPath in allAssetPaths)
        {
            Auxilliary.TryRegularizePath(relPath, out string regularizedPath);
            // FaceGen assets have no referencing record; PluginRef assets carry the record(s) that
            // referenced them (looked up by the raw path, which is what the prov map is keyed on,
            // and what headPartOnlyMeshPaths holds too).
            AssetRequestContext reqCtx = faceGenRelPaths.Contains(regularizedPath)
                ? faceGenCtx
                : pluginRefCtx.WithReferencer(LookupReferencer(assetProv, relPath));
            if (headPartOnlyMeshPaths.Contains(relPath)) reqCtx = reqCtx.AsHeadPartOnly();
            // This method is fire-and-forget; the task is added to the concurrent dictionary
            // and runs in the background. It will not re-process assets it has already seen.
            RequestAssetCopyAsync(regularizedPath, appearanceModSetting, outputBasePath, faceTexRelativePath, reqCtx);
        }
    }

    /// <summary>
    /// Schedules one half of an NPC's FaceGen from whichever source the ladder picked.
    /// <see cref="FaceGenSourceChoice.WinnerInPlace"/> and <see cref="FaceGenSourceChoice.None"/>
    /// are both no-ops by design: the first means the file the game already resolves is the one we
    /// want, and copying it would only pin a path the load order handles correctly on its own.
    /// </summary>
    private void ScheduleFaceGenHalf(
        FaceGenSourceChoice choice, string sourceRelPath, string destRelPath,
        ModSetting appearanceModSetting, string outputBasePath, string faceTintSubPath,
        AssetRequestContext ctx, string npcIdentifier)
    {
        switch (choice)
        {
            case FaceGenSourceChoice.AppearanceMod:
                RequestAssetCopyAsync(sourceRelPath, appearanceModSetting, outputBasePath,
                    faceTintSubPath, ctx, overrideDestinationRelativePath: destRelPath);
                break;

            case FaceGenSourceChoice.Origin:
            {
                var origin = FindOriginModSetting(GetSubjectModKey(sourceRelPath), sourceRelPath);
                if (origin == null)
                {
                    RunLog($"      WARNING: could not locate the mod that originally added {npcIdentifier}, " +
                           $"so its face file could not be copied.", false, true);
                    break;
                }

                RequestAssetCopyAsync(sourceRelPath, origin, outputBasePath,
                    faceTintSubPath, ctx.WithReason("FaceGenFromOrigin"), overrideDestinationRelativePath: destRelPath);
                break;
            }

            case FaceGenSourceChoice.Winner:
            {
                string absolute = Path.Combine(_environmentStateProvider.DataFolderPath,
                    sourceRelPath.Replace('/', '\\').TrimStart('\\'));
                if (!File.Exists(absolute))
                {
                    RunLog($"      WARNING: the face file already installed for {npcIdentifier} could not be " +
                           $"read back, so nothing was copied.", false, true);
                    break;
                }

                RequestAssetCopyAsync(sourceRelPath, appearanceModSetting, outputBasePath,
                    faceTintSubPath, ctx.WithReason("FaceGenFromWinner"),
                    overrideDestinationRelativePath: destRelPath,
                    explicitSourceAbsolutePath: absolute);
                break;
            }

            case FaceGenSourceChoice.WinnerInPlace:
            case FaceGenSourceChoice.None:
            default:
                break;
        }
    }

    /// <summary>Recovers the defining plugin from a FaceGen relative path, whose second-to-last
    /// segment is the plugin filename by construction (see
    /// <see cref="Auxilliary.GetFaceGenSubPathStrings"/>).</summary>
    private static ModKey GetSubjectModKey(string faceGenRelPath)
    {
        var segments = faceGenRelPath.Replace('/', '\\').Split('\\', StringSplitOptions.RemoveEmptyEntries);
        return segments.Length >= 2 ? ModKey.FromFileName(segments[^2]) : ModKey.Null;
    }

    /// <summary>
    /// Schedules asynchronous processing for assets identified via direct asset links.
    /// </summary>
    public async Task ScheduleCopyAssetLinkFiles(List<IAssetLinkGetter> assetLinks, ModSetting appearanceModSetting, string outputBasePath, string faceTexRelativePath,
        INpcGetter appearanceNpcRecord, FormKey targetNpcFormKey, string npcIdentifier)
    {
        using var _ = ContextualPerformanceTracer.Trace("AssetHandler.ScheduleCopyAssetLinkFiles");

        if (!appearanceModSetting.CopyAssets)
        {
            return;
        }

        var assetRelPaths =
            assetLinks
                .Select(x => x.GivenPath)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .Select(RegularizeOrSelf)
                .Where(rel => rel is not null)
                .Select(rel => rel!) // null-forgiving operator converts string? → string
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

        var ctx = new AssetRequestContext(npcIdentifier, targetNpcFormKey, appearanceNpcRecord.FormKey, appearanceNpcRecord.EditorID, "AssetLink");
        AddCorrespondingNumericalNifPaths(assetRelPaths, new HashSet<string>()); // safe to pass non-nif files because the function filters for .nif paths anyway
        foreach (var relPath in assetRelPaths)
        {
            if (relPath != null)
            {
                RequestAssetCopyAsync(relPath, appearanceModSetting, outputBasePath, faceTexRelativePath, ctx);
            }
        }
    }
    
    /// <summary>
    /// Schedules the file-side outputs of one wig→HeadPart conversion (see
    /// <see cref="HeadPartWigConverter"/>):
    /// <list type="bullet">
    /// <item>The wig NIF at its original data-relative path — it is the minted
    /// HDPT records' Model target. The normal copy pipeline post-processes it,
    /// which also scans it for textures and schedules its ORIGINAL physics XML —
    /// necessary because the FaceGen texture scan runs on the pre-bake copy and
    /// never sees the wig's textures.</item>
    /// <item>The REWRITTEN physics XML (shape entries renamed to the minted
    /// HeadPart EditorIDs, see <see cref="SmpXmlRewriter"/>) at the NPC2-owned
    /// path the baked FaceGen's physics extra-data points at, plus any sibling
    /// XML includes of the source config (same follow-up
    /// <see cref="PostProcessSmpXmlIncludes"/> the plain XML copy path runs).</item>
    /// </list>
    /// Deduped per (file, mod) through the same task cache as every other asset,
    /// so NPCs sharing a wig schedule the work once and
    /// <see cref="MonitorAndWaitForAllTasks"/> waits for it.
    /// </summary>
    public void ScheduleWigConversionAssets(HeadPartWigConverter.Result convertResult,
        ModSetting appearanceModSetting, string outputBasePath, string faceTintSubPath,
        FormKey targetNpcFormKey, INpcGetter appearanceNpcRecord, string npcIdentifier)
    {
        var ctx = new AssetRequestContext(npcIdentifier, targetNpcFormKey, appearanceNpcRecord.FormKey,
            appearanceNpcRecord.EditorID, "WigConvert");

        // 1. The wig NIF (HDPT Model target). PostProcessCopiedFile handles the
        //    texture scan + original-physics-XML follow-up when CopyAssets is on.
        _ = RequestAssetCopyAsync(convertResult.WigNifDataRelPath, appearanceModSetting, outputBasePath,
            faceTintSubPath, ctx);

        // 2. The rewritten physics XML (SMP wigs only).
        if (convertResult.PhysicsXmlSourcePath == null || convertResult.PhysicsXmlNewDataRelPath == null)
        {
            return;
        }

        string destRel = convertResult.PhysicsXmlNewDataRelPath;
        string sourcePath = convertResult.PhysicsXmlSourcePath;
        var renames = new Dictionary<string, string>(convertResult.ShapeRenames, StringComparer.OrdinalIgnoreCase);
        var xmlCtx = ctx.WithReason("WigConvert", Path.GetFileName(sourcePath));

        // Reference recorded per NPC (before the dedup) so the provenance report
        // lists every NPC the wig serves; the transform itself runs once.
        AssetProvenanceDiag.RecordReference(destRel, appearanceModSetting.DisplayName, xmlCtx);

        string cacheKey = $"{destRel}|{appearanceModSetting.DisplayName}";
        _processedAssetTasks.GetOrAdd(cacheKey, _ => Task.Run(() =>
        {
            try
            {
                string destPath = Path.Combine(outputBasePath, destRel);
                int renamed = SmpXmlRewriter.RewriteShapeNames(sourcePath, destPath, renames);
                AssetProvenanceDiag.RecordSource(destRel, appearanceModSetting.DisplayName,
                    "Generated", sourcePath);
                AppendLog($"      Wig conversion: wrote rewritten physics XML '{destRel}' " +
                          $"({renamed} shape entr{(renamed == 1 ? "y" : "ies")} renamed).", false, false);

                // Sibling includes of the SOURCE config (the rewrite only touches
                // shape names, so the include references are unchanged) — copied
                // at their original rel paths like the plain XML copy path does.
                PostProcessSmpXmlIncludes(sourcePath, appearanceModSetting, outputBasePath, faceTintSubPath, xmlCtx);
            }
            catch (Exception ex)
            {
                AppendLog($"      ERROR writing rewritten wig physics XML '{destRel}': " +
                          $"{ExceptionLogger.GetExceptionStack(ex)}", true, true);
            }
        }));
    }

    /// <summary>
    /// Waits for all scheduled asset operations to finish while providing periodic status updates.
    /// </summary>
    /// <param name="progressReporter">An action that will be called with a formatted status string.</param>
    public async Task MonitorAndWaitForAllTasks(Action<string> progressReporter)
    {
        int lastReportedCompleted = 0;
        int lastReportedTotal = _processedAssetTasks.Count;

        progressReporter($"Asset Transfer: Beginning final asset copy. {lastReportedTotal} initial files queued.");

        while (true)
        {
            // Create a task that completes only when all *currently known* tasks are finished.
            var allCurrentTasks = _processedAssetTasks.Values.ToList();
            var completionTask = Task.WhenAll(allCurrentTasks);

            // Create a delay task that acts as our 10-second timer.
            var timerTask = Task.Delay(TimeSpan.FromSeconds(10));

            // Wait for whichever finishes first: the 10-second timer, or all known tasks completing.
            await Task.WhenAny(completionTask, timerTask);

            // Get a snapshot of the current counts.
            int totalTasks = _processedAssetTasks.Count;
            int completedTasks = _processedAssetTasks.Values.Count(t => t.IsCompleted);

            // Check if all tasks that existed at the start of this loop are done, AND no new tasks have been added.
            // This is the condition for being truly finished.
            if (completionTask.IsCompleted && totalTasks == allCurrentTasks.Count)
            {
                break; // Exit the monitoring loop.
            }

            // If we are here, it's because the 10-second timer elapsed, or tasks finished but new ones were added.
            // Time to generate a progress report.
            int remaining = totalTasks - completedTasks;
            int processedSinceLast = completedTasks - lastReportedCompleted;
            int discoveredSinceLast = totalTasks - lastReportedTotal;

            progressReporter($"Asset Transfer: {remaining} remaining files ({completedTasks}/{totalTasks} total, {processedSinceLast} processed, {discoveredSinceLast} discovered since last report)");

            // Update our counters for the next report.
            lastReportedCompleted = completedTasks;
            lastReportedTotal = totalTasks;
        }

        progressReporter($"Asset Transfer: Complete. {_processedAssetTasks.Count} total assets processed.");
    }

    // --- Asset Identification Helpers ---
    // When the opt-in AssetProvenance diag is on, each helper is passed a path -> referencing-record
    // map (prov); every asset path it collects is tagged with the record that referenced it (head
    // part / armor addon / texture set) so the CSV report can name it. prov is null when the diag is off.
    // headPartOnlyMeshPaths (optional) receives the mesh paths that ONLY a HeadPart record named, so
    // the textureless-shape warning can skip them (see AssetRequestContext.HeadPartOnly). A path an
    // ArmorAddon also names is removed again at the end: worn armour really is drawn from its own
    // mesh, so it must stay reportable even when a head part happens to point at the same file.
    private void GetAssetPathsReferencedByPlugin(INpcGetter npc, IEnumerable<ModKey> correspondingModKeys, HashSet<string> fallBackModFolderNames, HashSet<string> meshPaths,
        HashSet<string> texturePaths, Dictionary<string, HashSet<string>>? prov, HashSet<string>? headPartOnlyMeshPaths = null)
    {
        var visitedHeadParts = new HashSet<FormKey>();

        if (npc.HeadParts != null)
            foreach (var hpLink in npc.HeadParts)
                GetHeadPartAssetPaths(hpLink, correspondingModKeys, fallBackModFolderNames, texturePaths, meshPaths, visitedHeadParts, prov, headPartOnlyMeshPaths);
        if (!npc.WornArmor.IsNull && _recordHandler.TryGetRecordFromMods(npc.WornArmor, correspondingModKeys, fallBackModFolderNames,
                RecordLookupFallBack.Winner, out var wornArmorGetterGeneric) && wornArmorGetterGeneric != null)
        {
            var wornArmorGetter = wornArmorGetterGeneric as IArmorGetter;
            if (wornArmorGetter != null && wornArmorGetter.Armature != null)
            {
                // Collected separately rather than diffed out of meshPaths: a path both records name
                // is already in the set, so the ARMA walk's Add is a no-op and a before/after
                // snapshot could not see it.
                var armaMeshPaths = headPartOnlyMeshPaths != null
                    ? new HashSet<string>(StringComparer.OrdinalIgnoreCase)
                    : null;

                foreach (var aaLink in wornArmorGetter.Armature)
                    GetARMAAssetPaths(aaLink, correspondingModKeys, fallBackModFolderNames, texturePaths, meshPaths, prov, armaMeshPaths);

                if (armaMeshPaths != null) headPartOnlyMeshPaths!.ExceptWith(armaMeshPaths);
            }
        }
    }

    private void GetHeadPartAssetPaths(IFormLinkGetter<IHeadPartGetter> hpLink, IEnumerable<ModKey> correspondingModKeys, HashSet<string> fallBackModFolderNames, HashSet<string> texturePaths,
        HashSet<string> meshPaths, HashSet<FormKey> visitedHeadParts, Dictionary<string, HashSet<string>>? prov, HashSet<string>? headPartMeshPaths = null)
    {
        if (hpLink.IsNull || !_recordHandler.TryGetRecordFromMods(hpLink, correspondingModKeys, fallBackModFolderNames, RecordLookupFallBack.Winner, out var hpGetterGeneric)) return;
        var hpGetter = hpGetterGeneric as IHeadPartGetter;
        if (hpGetter is null) return;

        //  PREVENT CIRCULAR REFERENCES
        // If we can't add the FormKey, it means we've already processed this HeadPart.
        if (!visitedHeadParts.Add(hpGetter.FormKey))
        {
            return; // Break the recursive loop
        }

        AddPathWithProv(meshPaths, hpGetter.Model?.File, prov, hpGetter, headPartMeshPaths);
        if (hpGetter.Parts != null)
            foreach (var part in hpGetter.Parts)
                AddPathWithProv(meshPaths, part?.FileName, prov, hpGetter, headPartMeshPaths);
        if (!hpGetter.TextureSet.IsNull) GetTextureSetPaths(hpGetter.TextureSet, correspondingModKeys, fallBackModFolderNames, texturePaths, prov);
        if (hpGetter.ExtraParts != null)
            foreach (var extraPartLink in hpGetter.ExtraParts)
                GetHeadPartAssetPaths(extraPartLink, correspondingModKeys, fallBackModFolderNames, texturePaths, meshPaths, visitedHeadParts, prov, headPartMeshPaths);
    }

    private void GetARMAAssetPaths(IFormLinkGetter<IArmorAddonGetter> aaLink, IEnumerable<ModKey> correspondingModKeys, HashSet<string> fallBackModFolderNames, HashSet<string> texturePaths,
        HashSet<string> meshPaths, Dictionary<string, HashSet<string>>? prov, HashSet<string>? armaMeshPaths = null)
    {
        if (aaLink.IsNull || !_recordHandler.TryGetRecordFromMods(aaLink, correspondingModKeys, fallBackModFolderNames, RecordLookupFallBack.Winner, out var aaGetterGeneric)) return;
        var aaGetter = aaGetterGeneric as IArmorAddonGetter;
        if (aaGetter is null) return;

        AddPathWithProv(meshPaths, aaGetter.WorldModel?.Male?.File, prov, aaGetter, armaMeshPaths);
        AddPathWithProv(meshPaths, aaGetter.WorldModel?.Female?.File, prov, aaGetter, armaMeshPaths);
        if (!aaGetter.SkinTexture?.Male.IsNull ?? false)
            GetTextureSetPaths(aaGetter.SkinTexture.Male, correspondingModKeys, fallBackModFolderNames, texturePaths, prov);
        if (!aaGetter.SkinTexture?.Female.IsNull ?? false)
            GetTextureSetPaths(aaGetter.SkinTexture.Female, correspondingModKeys, fallBackModFolderNames, texturePaths, prov);
    }

    private void GetTextureSetPaths(IFormLinkGetter<ITextureSetGetter> txstLink, IEnumerable<ModKey> correspondingModKeys, HashSet<string> fallBackModFolderNames,  HashSet<string> texturePaths, Dictionary<string, HashSet<string>>? prov)
    {
        if (txstLink.IsNull ||
            !_recordHandler.TryGetRecordFromMods(txstLink, correspondingModKeys, fallBackModFolderNames, RecordLookupFallBack.Winner, out var txstGetterGeneric)) return;
        var txstGetter = txstGetterGeneric as ITextureSetGetter;
        if (txstGetter is null) return;

        AddPathWithProv(texturePaths, txstGetter.Diffuse?.GivenPath, prov, txstGetter);
        AddPathWithProv(texturePaths, txstGetter.NormalOrGloss?.GivenPath, prov, txstGetter);
        AddPathWithProv(texturePaths, txstGetter.EnvironmentMaskOrSubsurfaceTint?.GivenPath, prov, txstGetter);
        AddPathWithProv(texturePaths, txstGetter.GlowOrDetailMap?.GivenPath, prov, txstGetter);
        AddPathWithProv(texturePaths, txstGetter.Height?.GivenPath, prov, txstGetter);
        AddPathWithProv(texturePaths, txstGetter.Environment?.GivenPath, prov, txstGetter);
        AddPathWithProv(texturePaths, txstGetter.Multilayer?.GivenPath, prov, txstGetter);
        AddPathWithProv(texturePaths, txstGetter.BacklightMaskOrSpecular?.GivenPath, prov, txstGetter);
    }

    // Adds relPath to the given set (if non-empty) and — when the AssetProvenance diag is on
    // (prov != null) — tags it with the record that referenced it, so the report can say exactly
    // which head part / armor addon / texture set pulled the file in. alsoAddTo is the caller's
    // per-record-kind set (head part meshes / ARMA meshes), tracked independently of the diag
    // because the textureless-shape warning reads it on every run.
    private static void AddPathWithProv(HashSet<string> pathSet, string? relPath, Dictionary<string, HashSet<string>>? prov, IMajorRecordGetter owner,
        HashSet<string>? alsoAddTo = null)
    {
        if (string.IsNullOrEmpty(relPath)) return;
        pathSet.Add(relPath);
        alsoAddTo?.Add(relPath);
        if (prov == null) return;
        if (!prov.TryGetValue(relPath, out var owners))
        {
            owners = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            prov[relPath] = owners;
        }
        owners.Add(DescribeRecordForProv(owner));
    }

    // "HeadPart 'EditorID' [FormKey]" (or "HeadPart [FormKey]" when no EditorID) for the provenance report.
    private static string DescribeRecordForProv(IMajorRecordGetter rec)
    {
        string type = rec switch
        {
            IHeadPartGetter => "HeadPart",
            IArmorAddonGetter => "ArmorAddon",
            IArmorGetter => "Armor",
            ITextureSetGetter => "TextureSet",
            _ => "Record"
        };
        return string.IsNullOrEmpty(rec.EditorID)
            ? $"{type} [{rec.FormKey}]"
            : $"{type} '{rec.EditorID}' [{rec.FormKey}]";
    }

    // Looks up the referencing-record descriptor(s) for a plugin-referenced asset, joined with " | ".
    // For an auto-added _0/_1 body-double NIF (which has no direct reference of its own) it falls
    // back to its sibling's records. Returns empty when the diag is off or nothing is recorded.
    private static string LookupReferencer(Dictionary<string, HashSet<string>>? prov, string relPath)
    {
        if (prov == null) return string.Empty;
        if (prov.TryGetValue(relPath, out var owners) && owners.Count > 0)
            return string.Join(" | ", owners.OrderBy(x => x, StringComparer.OrdinalIgnoreCase));

        string? sibling = null;
        if (relPath.EndsWith("_0.nif", StringComparison.OrdinalIgnoreCase)) sibling = relPath.Substring(0, relPath.Length - 6) + "_1.nif";
        else if (relPath.EndsWith("_1.nif", StringComparison.OrdinalIgnoreCase)) sibling = relPath.Substring(0, relPath.Length - 6) + "_0.nif";
        if (sibling != null && prov.TryGetValue(sibling, out var sibOwners) && sibOwners.Count > 0)
            return string.Join(" | ", sibOwners.OrderBy(x => x, StringComparer.OrdinalIgnoreCase));

        return string.Empty;
    }

    // --- Asset Copying/Extraction Helpers ---
    
    /// <summary>
    /// Returns the direct sub-directories of <paramref name="rootDir"/> that contain
    /// <paramref name="relativeFilePath"/> (e.g.  "Textures\Foo.png").
    /// Only the first level of sub-directories is inspected—no recursion.
    /// </summary>
    public static string[] GetContainingSubdirectories(
        string rootDir,
        string relativeFilePath)
    {
        if (rootDir is null) throw new ArgumentNullException(nameof(rootDir));
        if (relativeFilePath is null) throw new ArgumentNullException(nameof(relativeFilePath));

        return Directory // 1️⃣  list immediate sub-folders
            .EnumerateDirectories(rootDir, "*", SearchOption.TopDirectoryOnly)
            .Where(subDir => // 2️⃣  keep those that contain the file
                File.Exists(Path.Combine(subDir, relativeFilePath)))
            .ToArray(); // 3️⃣  materialise as string[]
    }

    /// <summary>
    /// Copies loose asset files, checking all source directories.
    /// **Revised for Clarification 2.**
    /// </summary>
    private Dictionary<string, bool> CopyAssetFiles(List<string> sourceDataDirPaths,
        HashSet<string> assetRelativePathList,
        string assetType /*"Meshes" or "Textures"*/, string sourcePluginName,
        IEnumerable<string> autoPredictedExtraPaths, string outputBaseDirPath)
    {
        Dictionary<string, bool> result = new();

        string outputBase = Path.Combine(outputBaseDirPath, assetType);
        Directory.CreateDirectory(outputBase);

        var warningsToSuppressSet = _warningsToSuppress_Global;
        string pluginKeyLower = sourcePluginName.ToLowerInvariant();
        if (_warningsToSuppress.TryGetValue(pluginKeyLower, out var specificWarnings))
        {
            warningsToSuppressSet = specificWarnings;
        }

        warningsToSuppressSet.UnionWith(autoPredictedExtraPaths);

        foreach (string relativePath in assetRelativePathList)
        {
            result[relativePath] = false;
            if (IsIgnored(relativePath, _pathsToIgnore)) continue;

            string? foundSourcePath = null;
            // Check Source Directories
            foreach (var sourcePathBase in sourceDataDirPaths)
            {
                string potentialPath = Path.Combine(sourcePathBase, assetType, relativePath);
                if (File.Exists(potentialPath))
                {
                    foundSourcePath = potentialPath;
                    break; // Found it
                }
            }

            // Check Game Data Folder (if configured and not FaceGen)
            bool isFaceGen = relativePath.Contains("facegendata", StringComparison.OrdinalIgnoreCase);
            if (foundSourcePath == null && _getMissingExtraAssetsFromAvailableWinners && !isFaceGen)
            {
                string gameDataPath = Path.Combine(_environmentStateProvider.DataFolderPath.ToString(), assetType,
                    relativePath);
                if (File.Exists(gameDataPath))
                {
                    foundSourcePath = gameDataPath;
                    RunLog(
                        $"        Found missing asset '{relativePath}' in game data folder."); // Verbose only
                }
            }

            if (foundSourcePath == null)
            {
                // Handle Missing File Warning/Error
                bool suppressWarning = _suppressAllMissingFileWarnings ||
                                       (_suppressKnownMissingFileWarnings &&
                                        warningsToSuppressSet.Contains(relativePath)) ||
                                       GetExtensionOfMissingFile(relativePath) == ".tri";
                if (!suppressWarning)
                {
                    string errorMsg = $"Asset '{relativePath}' not found in any source directories";
                    if (_getMissingExtraAssetsFromAvailableWinners && !isFaceGen) errorMsg += " or game data folder";
                    errorMsg += $" (needed by {sourcePluginName}).";
                    RunLog($"      WARNING: {errorMsg}"); // Verbose only (Warning)
                }
            }
            else
            {
                // Copy the found file
                string destPath = Path.Combine(outputBase, relativePath);
                try
                {
                    FileInfo fileInfo = Auxilliary.CreateDirectoryIfNeeded(destPath, Auxilliary.PathType.File);
                    File.Copy(foundSourcePath, destPath, true);
                    result[relativePath] = true;
                }
                catch (Exception ex)
                {
                    RunLog(
                        $"      ERROR copying '{foundSourcePath}' to '{destPath}': {ExceptionLogger.GetExceptionStack(ex)}",
                        true);
                }
            }
        }

        return result;
    }

    // "The ArmorAddon should always point to the _1.nifs, so if they aren't I suggest you change it."
    // https://forums.nexusmods.com/topic/11698578-_1nif-not-detected/
    // Also from personal testing, it works the other way as well - if the corresponding _0.nif file is missing, a mesh
    // will (or at least can) turn invisible
    public static void AddCorrespondingNumericalNifPaths(HashSet<string> relativeNifPaths, HashSet<string> addedRelPaths)
    {
        // Manually add corresponding numerical nif paths if they don't already exist
        var iterableRelativePaths = relativeNifPaths.ToList();
        for (int i = 0; i < iterableRelativePaths.Count; i++)
        {
            string relPath = iterableRelativePaths[i];
            string replacedPath = string.Empty;
            if (relPath.EndsWith("_0.nif"))
            {
                replacedPath = relPath.Replace("_0.nif", "_1.nif");
                if (!relativeNifPaths.Contains(replacedPath))
                {
                    relativeNifPaths.Add(replacedPath);
                    addedRelPaths.Add(replacedPath);
                }
            }
            else if (relPath.EndsWith("_1.nif"))
            {
                replacedPath = relPath.Replace("_1.nif", "_0.nif");
                if (!relativeNifPaths.Contains(replacedPath))
                {
                    relativeNifPaths.Add(replacedPath);
                    addedRelPaths.Add(replacedPath);
                }
            }
        }
    }

    private bool IsIgnored(string relativePath, HashSet<string> toIgnore)
    {
        // (Implementation remains the same as before)
        return toIgnore.Contains(relativePath);
    }

    private string GetExtensionOfMissingFile(string input)
    {
        // (Implementation remains the same as before)
        if (string.IsNullOrEmpty(input))
        {
            return "";
        }

        return Path.GetExtension(input).ToLowerInvariant();
    }

    private bool LoadAuxiliaryFiles()
    {
        RunLog("Loading auxiliary configuration files..."); // Verbose only
        bool success = true;
        // **Correction 3:** Use Resources path
        string resourcesPath = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "Resources");

        // Load Ignored Paths
        _pathsToIgnore.Clear();
        string ignorePathFile = Path.Combine(resourcesPath, "Paths To Ignore.json"); // Corrected path
        if (File.Exists(ignorePathFile))
        {
            try
            {
                var tempList =
                    JSONhandler<List<string>>.LoadJSONFile(ignorePathFile, out bool loadSuccess, out string loadEx);
                if (loadSuccess && tempList != null)
                {
                    _pathsToIgnore = new HashSet<string>(tempList.Select(p => p.Replace(@"\\", @"\")),
                        StringComparer.OrdinalIgnoreCase);
                    RunLog($"Loaded {_pathsToIgnore.Count} paths to ignore."); // Verbose only
                }
                else
                {
                    throw new Exception(loadEx);
                }
            }
            catch (Exception ex)
            {
                // **Correction 4:** Use ExceptionLogger
                RunLog(
                    $"WARNING: Could not load or parse '{ignorePathFile}'. No paths will be ignored. Error: {ExceptionLogger.GetExceptionStack(ex)}"); // Verbose only (Warning)
            }
        }
        else
        {
            RunLog(
                $"INFO: Ignore paths file not found at '{ignorePathFile}'. No paths will be ignored."); // Verbose only
        }


        // Load Suppressed Warnings
        _warningsToSuppress.Clear();
        _warningsToSuppress_Global.Clear();
        string suppressWarningsFile = Path.Combine(resourcesPath, "Warnings To Suppress.json"); // Corrected path
        if (File.Exists(suppressWarningsFile))
        {
            try
            {
                var tempList = JSONhandler<List<SuppressedWarnings>>.LoadJSONFile(suppressWarningsFile,
                    out bool loadSuccess, out string loadEx);
                if (loadSuccess && tempList != null)
                {
                    foreach (var sw in tempList)
                    {
                        var cleanedPaths = new HashSet<string>(sw.Paths.Select(p => p.Replace(@"\\", @"\")),
                            StringComparer.OrdinalIgnoreCase);
                        string pluginKeyLower = sw.Plugin.ToLowerInvariant();

                        if (pluginKeyLower == "global")
                        {
                            _warningsToSuppress_Global = cleanedPaths;
                        }
                        else
                        {
                            _warningsToSuppress[pluginKeyLower] = cleanedPaths;
                        }
                    }

                    RunLog(
                        $"Loaded suppressed warnings for {_warningsToSuppress.Count} specific plugins and global scope."); // Verbose only
                }
                else
                {
                    throw new Exception(loadEx);
                }
            }
            catch (Exception ex)
            {
                // **Correction 4:** Use ExceptionLogger
                RunLog(
                    $"ERROR: Could not load or parse '{suppressWarningsFile}'. Suppressed warnings will not be used. Error: {ExceptionLogger.GetExceptionStack(ex)}",
                    true);
                success = false;
            }
        }
        else
        {
            // Neutral and non-error on purpose (user standard, 2026-08-02): the suppression list
            // only silences known-missing-asset reports, so its absence makes NPC2 say MORE, not
            // less, and changes nothing the user sees in game. "Cannot proceed" was untrue as
            // well — LoadAuxiliaryFiles' result is not acted on and the run continues. Forced
            // rather than verbose because a missing shipped resource means a damaged install,
            // which is worth saying once; see Patcher.LogOrphanedDuplicates for the shape.
            RunLog(
                $"Note: no suppression list at '{suppressWarningsFile}' (one ships with NPC2), so " +
                "every missing asset will be reported. Patching is unaffected.",
                false, true);
            success = false;
        }

        return success;
    }
