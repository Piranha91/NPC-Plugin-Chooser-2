"""NPC2 in-game pre-release check: corpus custody. The corpus folder is outside both repositories.

  python bench_corpus.py freeze      copy the corpus mods out of the instance, hash every file, write the lists
  python bench_corpus.py verify      instance files against the manifest (size + mtime first, hash on any doubt)
  python bench_corpus.py verify --full     hash every instance file against the manifest
  python bench_corpus.py verify --corpus   hash the corpus copy itself against the manifest

Layout of B.CORPUS:
  mods/<folder>/...            the copies (High Poly's main folder and Nordic Faces keep only the subjects' FaceGen)
  MANIFEST.json                {relative path: {sha256, size, mtime}}
  corpus.json, CORPUS.md       NPCs, mods, mod versions, tools
  npc2-settings-snapshot.json  NPC2's persisted analysis of these mods (the source of every staged Settings.json)

A changed byte stops a run and names the file: bench_run.go() calls verify() before every launch."""
import configparser, hashlib, json, os, re, shutil, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bench_def as B

MANIFEST = os.path.join(B.CORPUS, "MANIFEST.json")
PRUNED = {"HPNO": 1, "NF": 0}      # mod key -> index of the folder whose per-NPC FaceGen is pruned to the subjects
FACEGEN = re.compile(r"facegendata[\\/](facegeom|facetint)[\\/][^\\/]+[\\/]([0-9a-f]{8})\.(nif|dds)$", re.I)


def corpus_folders():
    """[(mod key or role, instance folder name, prune?)] in a stable order, no duplicates."""
    d, _ = B.snapshot()
    out, seen = [], set()
    def add(role, folder, prune=False):
        if folder not in seen:
            seen.add(folder); out.append((role, folder, prune))
    for key, display in B.MOD.items():
        for i, f in enumerate(B.mod_folders(d, key)):
            add(key, f, PRUNED.get(key) == i)
    for f in B.BASE_MODS: add("base", f)
    for f in B.PATCHED: add("environment", f)
    for f in B.CONTEST: add("contest", f)
    for f in B.TOOLS: add("tool", f)
    add("physics", B.SMP)
    return out


def subject_forms():
    return {B.S[n][0].lower().zfill(8) for n in B.S}


def keep(rel, prune, forms):
    if not prune:
        return True
    m = FACEGEN.search(rel)
    return not m or m.group(2).lower() in forms


def sha_file(path, copy_to=None):
    h = hashlib.sha256()
    out = open(copy_to, "wb") if copy_to else None
    with open(path, "rb") as f:
        while True:
            b = f.read(1 << 22)
            if not b:
                break
            h.update(b)
            if out:
                out.write(b)
    if out:
        out.close()
        shutil.copystat(path, copy_to)
    return h.hexdigest()


def meta(folder):
    p = os.path.join(B.MODS_DIR, folder, "meta.ini")
    if not os.path.exists(p):
        return {}
    cp = configparser.RawConfigParser(strict=False)
    try:
        cp.read(p, encoding="utf-8-sig")
        g = cp["General"]
        return {k: g.get(k, "") for k in ("version", "modid", "installationFile", "newestVersion")}
    except Exception as e:
        return {"error": repr(e)}


def freeze():
    forms = subject_forms()
    os.makedirs(os.path.join(B.CORPUS, "mods"), exist_ok=True)
    # the settings snapshot first: everything below reads mod folders from it
    live = json.load(open(B.LIVE_SETTINGS, encoding="utf-8-sig"))
    wanted = set(B.MOD.values())
    snap = {k: v for k, v in live.items() if k != "ModSettings"}
    snap["ModSettings"] = [m for m in live["ModSettings"] if m["DisplayName"] in wanted or m.get("IsAutoGenerated")]
    for m in snap["ModSettings"]:
        m["LastKnownState"] = None
    snap["SelectedAppearanceMods"] = {}
    for k in ("NpcOutfitOverrides", "HiddenModsPerNpc", "NpcRenderOverrides", "FavoriteFacesGroupAssignments"):
        if k in snap:
            snap[k] = type(snap[k])()
    if not os.path.exists(B.SNAPSHOT):
        json.dump(snap, open(B.SNAPSHOT, "w", encoding="utf-8"), indent=1)
    manifest = json.load(open(MANIFEST)) if os.path.exists(MANIFEST) else {}
    mods = []
    for role, folder, prune in corpus_folders():
        src = os.path.join(B.MODS_DIR, folder)
        n = size = skipped = 0
        t0 = time.time()
        for root, _, files in os.walk(src):
            for fn in files:
                p = os.path.join(root, fn)
                rel = os.path.relpath(p, B.MODS_DIR).replace("\\", "/")
                if not keep(rel, prune, forms):
                    skipped += 1
                    continue
                dst = os.path.join(B.CORPUS, "mods", rel.replace("/", os.sep))
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                st = os.stat(p)
                had = manifest.get(rel)
                if not (had and had["size"] == st.st_size and had["mtime"] == int(st.st_mtime) and os.path.exists(dst)):
                    manifest[rel] = {"sha256": sha_file(p, dst), "size": st.st_size, "mtime": int(st.st_mtime)}
                n += 1; size += st.st_size
        plugins = sorted(f for f in os.listdir(src) if f.lower().endswith((".esp", ".esm", ".esl")))
        mods.append({"role": role, "folder": folder, "files": n, "bytes": size, "prunedFiles": skipped, "plugins": plugins, **meta(folder)})
        print(f"{folder}: {n} files, {size / 1e9:.2f} GB, pruned {skipped}, {time.time() - t0:.0f}s", flush=True)
        json.dump(manifest, open(MANIFEST, "w"), indent=0)
    write_lists(mods)
    print("frozen:", len(manifest), "files,", round(sum(v["size"] for v in manifest.values()) / 1e9, 2), "GB")


def write_lists(mods):
    d, _ = B.snapshot()
    npcs = []
    for name, (form, plugin, mk, tg) in B.S.items():
        e = B.mod_entry(d, B.MOD[mk]) if mk else None
        npcs.append({"name": name, "formKey": f"{form}:{plugin}", "mod": B.MOD.get(mk), "modKey": mk, "tags": tg,
                     "displayName": (e or {}).get("NpcFormKeysToDisplayName", {}).get(f"{form}:{plugin}"),
                     "launches": [l for l in B.LAUNCHES if name in [s["name"] for s in B.launch_subjects(l)]]})
    by_key = {}
    for m in mods:
        by_key.setdefault(m["role"], []).append(m)
    doc = {"frozen": time.strftime("%Y-%m-%d %H:%M:%S"), "instance": B.INSTANCE, "npcs": npcs, "mods": mods,
           "appearanceMods": {k: {"displayName": v, "folders": [m["folder"] for m in by_key.get(k, [])]} for k, v in B.MOD.items()}}
    json.dump(doc, open(os.path.join(B.CORPUS, "corpus.json"), "w", encoding="utf-8"), indent=1)
    L = ["# NPC2 bench corpus", "", f"Frozen {doc['frozen']} from `{B.INSTANCE}`. Hashes: `MANIFEST.json`.", "",
         "## Mods", "", "| Role | Folder | Version | Nexus ID | Installed from | Plugins | Files | GB | FaceGen pruned |", "|---|---|---|---|---|---|---|---|---|"]
    for m in mods:
        L.append(f"| {m['role']} | {m['folder']} | {m.get('version', '')} | {m.get('modid', '')} | {m.get('installationFile', '')} | "
                 f"{', '.join(m['plugins'])} | {m['files']} | {m['bytes'] / 1e9:.2f} | {m['prunedFiles'] or ''} |")
    L += ["", "## NPCs", "", "| NPC | FormKey | Appearance mod | Tags | Launches |", "|---|---|---|---|---|"]
    for n in npcs:
        L.append(f"| {n['name']} | {n['formKey']} | {n['mod'] or '(not selected: observer)'} | {n['tags']} | {' '.join(n['launches'])} |")
    open(os.path.join(B.CORPUS, "CORPUS.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")


def verify(full=False, corpus=False, quiet=False):
    """Paths that no longer match the manifest (empty list = intact). No manifest yet = nothing to verify."""
    if not os.path.exists(MANIFEST):
        if not quiet:
            print("no manifest yet: corpus not frozen")
        return []
    manifest = json.load(open(MANIFEST))
    root = os.path.join(B.CORPUS, "mods") if corpus else B.MODS_DIR
    bad = []
    for rel, rec in manifest.items():
        p = os.path.join(root, rel.replace("/", os.sep))
        if not os.path.exists(p):
            bad.append(f"MISSING {rel}"); continue
        st = os.stat(p)
        if st.st_size != rec["size"]:
            bad.append(f"SIZE {rel}"); continue
        if full or corpus or int(st.st_mtime) != rec["mtime"]:
            if sha_file(p) != rec["sha256"]:
                bad.append(f"HASH {rel}")
    if not quiet:
        print(f"verified {len(manifest)} files under {root}: {'intact' if not bad else str(len(bad)) + ' CHANGED'}")
        for b in bad[:40]:
            print(" ", b)
    return bad


if __name__ == "__main__":
    a = sys.argv[1:]
    if a[:1] == ["freeze"]:
        freeze()
    elif a[:1] == ["verify"]:
        sys.exit(1 if verify(full="--full" in a, corpus="--corpus" in a) else 0)
    else:
        sys.exit(__doc__)
